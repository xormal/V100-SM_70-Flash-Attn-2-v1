// Отладочный замер по фазам выключен: здесь он бессмыслен, фазы теперь РАЗНЕСЕНЫ ПО ВАРПАМ, а не
// идут одна за другой в одном потоке.
// [КРУПНЫЙ ЗАМЕР ФАЗ РОЛЕЙ] Сколько каждая группа СТОИТ и сколько РАБОТАЕТ. Читать пропорции.
#if FA2_PHASE
#define PH_DECL long long _pht = clock64(); long long _phacc[8] = {0,0,0,0,0,0,0,0};
#define PH(i)   do { long long _n = clock64(); _phacc[i] += _n - _pht; _pht = _n; } while (0)
#define PH_OUT(dst) do { if ((threadIdx.x & 31) == 0) { for (int _i = 0; _i < 8; ++_i) \
                    atomicAdd(reinterpret_cast<unsigned long long*>(dst) + _i, \
                              (unsigned long long)_phacc[_i]); } } while (0)
#else
#define PH_DECL
#define PH(i)
#define PH_OUT(dst)
#endif
#define FA2_DUNROLL 1
#define FA2_TPCROT 0
