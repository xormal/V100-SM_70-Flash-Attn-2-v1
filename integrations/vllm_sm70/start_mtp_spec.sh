#!/usr/bin/env bash
# Поднять модель со СПЕКУЛЯТИВНЫМ ДЕКОДОМ на встроенной MTP-голове.
#
# ЗАЧЕМ. Декод памятный: на карту за проход читается 13.862 ГиБ (слои 12.678 + голова 1.184), это
# 17.7 мс при достижимых 841 ГБ/с, то есть крыша 57 ток/с; замерено 35.1. Токен раскладывается
# почти без остатка: 17.7 веса + 9.0 обмен (128 событий) + 1.8 прочее = 28.5 мс.
# Спекуляция НЕ повышает КПД -- она ломает постановку: за ОДНО чтение весов получается несколько
# токенов. Поэтому она обходит крышу 57, а не приближается к ней.
#
# ПОЧЕМУ ЭТО НЕ СТОИТ ТОЧНОСТИ. Проверка принимает черновой токен только если он совпадает с тем,
# что дала бы полная модель (при жадном декоде) либо проходит выборку по отношению вероятностей
# (при сэмплировании). Выход ТОЖДЕСТВЕНЕН недвусмысленно, а не "в пределах бюджета". Именно поэтому
# bench_mtp_spec.py первым делом сверяет ЖАДНУЮ выдачу со спекуляцией и без -- она обязана совпасть
# посимвольно, и если не совпала, все цифры скорости недействительны.
#
# ЧТО В СЛЕПКЕ УЖЕ ЕСТЬ (проверено по заголовкам safetensors, ничего строить не надо):
#   mtp.fc.weight                       [5120, 10240]  100 МиБ   сращивание вложения и состояния
#   mtp.layers.0.self_attn.q_proj       [12288, 5120]  120 МиБ   (воротная: attn_output_gate)
#   mtp.layers.0.self_attn.{k,v}_proj   [1024, 5120]    10 МиБ каждая
#   mtp.layers.0.self_attn.o_proj       [5120, 6144]    60 МиБ
#   mtp.layers.0.mlp.{gate,up,down}     ...            170 МиБ каждая
#   плюс нормировки -- всего 810 МиБ bf16
# config.text_config.mtp_num_hidden_layers = 1.
#
# ТРИ УСЛОВИЯ, БЕЗ КОТОРЫХ НЕ ЗАГРУЗИТСЯ (каждое проверено в коде, а не предположено):
#   1. В quantization_config.modules_to_not_convert должен быть "mtp" -- иначе vLLM создаст для
#      ветки черновика qweight/qzeros, которых в слепке нет. У НАС ЕСТЬ (см. config.json).
#      Ветка отключения квантования: models/qwen3_5_mtp.py, _mtp_quant_disabled_in_hf_config.
#   2. ПРЕФИКС-КЭШ И СПЕКУЛЯЦИЯ ВЗАИМОИСКЛЮЧАЮЩИ. Это было записано здесь НЕВЕРНО ("по умолчанию
#      none, то есть штатно") и стоило сорванного задания: сервер умирал через 8 с, ДО загрузки
#      весов, с pydantic ValidationError "Mamba cache mode 'align' is currently not compatible with
#      speculative decoding". Цепочка: родительский start_model_fa2sm70_gpu23.sh жёстко передаёт
#      --enable-prefix-caching -> models/config.py:337 ставит mamba_cache_mode='align' (эта модель
#      не поддерживает 'all') -> models/config.py:356 содержит assert not speculative_config.
#      Поэтому ниже безусловно добавляется --no-enable-prefix-caching (в списке аргументов EXTRA_ARGS
#      идёт ПОСЛЕ --enable-prefix-caching, и для BooleanOptionalAction побеждает последний).
#      ЦЕНА РЕШЕНИЯ НЕ НУЛЕВАЯ И ЭТО РЕЖИМНЫЙ ВЫБОР, а не улучшение: префикс-кэш на повторяющемся
#      префиксе даёт TTFT 44.5 -> 1.4 с (замерено), спекуляция даёт x1.47 на декоде (замерено, B=1).
#      Что выгоднее -- зависит от боевого профиля заявок. По умолчанию НЕ включать.
#      Побочно теряется min_p-сэмплирование.
#   3. Откат состояния 48 линейных слоёв при ОТКЛОНЕНИИ черновика обязателен, иначе рекуррентное
#      состояние уедет и выход испортится не сразу, а через десятки токенов. В этой сборке он есть:
#      v1/attention/backends/gdn_attn.py. Это главный риск гибридной модели, и он закрыт не нами.
#
# ПОБОЧНЫЙ ВЫИГРЫШ: асинхронное планирование в vLLM разрешено ТОЛЬКО с EAGLE/MTP-спекуляцией
# (config/vllm.py: "async scheduling is only supported with EAGLE/MTP kind of speculative decoding")
# и при таком методе включается само. Наш префикс-кэш на мамба-слоях его глушил (задача #62).
#
# РАСЧЁТ, который этот запуск проверяет (черновик на карту = 0.396 слой + 1.184 своя голова =
# 1.580 ГиБ на набросок; ожидание принятых за шаг = 1 + a + a^2 + ...):
#     k    принятие 0.5   0.7    0.85
#     1       x1.40      x1.59  x1.73
#     2       x1.53      x1.92  x2.25
#     3       x1.55      x2.09  x2.63
#     4       x1.51      x2.16  x2.89
# Весь расчёт висит на РЕАЛЬНОМ принятии -- его и надо замерить, оно не предполагается.
# ВНИМАНИЕ: при k>1 растёт не только выигрыш, но и размер проверяемой пачки. Список захвата графов
# обязан содержать (k+1)*B для всех нужных B, иначе декод падёт в eager (6.1 ток/с) и замер станет
# бессмысленным -- он покажет не спекуляцию, а потерю графов.
#
# ЗАПУСК:
#   K=3 PORT=8093 GPU_UTIL=0.90 CUDA_VISIBLE_DEVICES=0,1 \
#   VLLM_ROOT=/path/to/vllm MODEL=/path/to/model \
#   QUANT=gptq USE_SHIM=1 ./start_mtp_spec.sh
set -euo pipefail
SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"

K="${K:-3}"                          # число набросков за шаг
MAX_NUM_SEQS="${MAX_NUM_SEQS:-32}"

# Список размеров для захвата графов: (K+1)*B по всем B, которые нужны замеру батча. Без этого
# либо спекуляция, либо высокий батч уедут в eager, и мы измерим не то, что думаем.
CAP="$(python3 - "$K" "$MAX_NUM_SEQS" <<'PY'
import sys
k, mx = int(sys.argv[1]), int(sys.argv[2])
sizes = set()
for b in (1, 2, 4, 8, 16, 32):
    if b > mx: continue
    sizes.add(b)              # проверочная пачка без спекуляции
    sizes.add((k + 1) * b)    # и со спекуляцией
print("[" + ",".join(str(s) for s in sorted(s for s in sizes if s <= 4 * mx)) + "]")
PY
)"

export MAX_NUM_SEQS
# --no-enable-prefix-caching ОБЯЗАТЕЛЕН и идёт первым: без него сервер не поднимается вовсе (см. §2
# в шапке). Отключается только через SPEC_KEEP_PREFIX=1 -- и тогда подъём ГАРАНТИРОВАННО упадёт,
# оставлено лишь чтобы воспроизвести отказ.
PFX="--no-enable-prefix-caching"; [ "${SPEC_KEEP_PREFIX:-0}" = "1" ] && PFX=""
export EXTRA_ARGS="${EXTRA_ARGS:-} ${PFX} --speculative-config {\"method\":\"qwen3_5_mtp\",\"num_speculative_tokens\":${K}} --compilation-config {\"cudagraph_mode\":\"full_and_piecewise\",\"cudagraph_capture_sizes\":${CAP}}"

echo "[mtp] набросков k=$K, max_num_seqs=$MAX_NUM_SEQS, захват графов $CAP" >&2
echo "[mtp] ПРОВЕРЬ В ЛОГЕ, прежде чем верить любой цифре скорости:" >&2
echo "      1) 'Qwen3_5MTP: disabling quantization for MTP branch' -- черновик грузится без кванта" >&2
echo "      2) 'loaded N tensors' у Qwen3_5MultiTokenPredictor, и NO 'missing params'" >&2
echo "      3) 'Asynchronous scheduling is enabled' -- побочный выигрыш от MTP" >&2
echo "      4) НЕТ 'falling back to eager' при захвате графов" >&2

exec "$SCRIPT_DIR/start_model_fa2sm70_gpu23.sh"
