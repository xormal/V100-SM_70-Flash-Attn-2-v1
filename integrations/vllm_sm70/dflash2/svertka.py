# Разбор (см. RECEPT_PORTA_DFLASH §13):
#   * `base_kernel[side]` -- ось 0 это СТОРОНА: свёртка применяется ДВАЖДЫ за слой, ДО блока и
#     ПОСЛЕ него. «Двухтактная» -- про два ПРИМЕНЕНИЯ, а не про два отсчёта;
#   * оставшееся [taps, hidden] разворачивается в [taps, групп, размер_группы];
#   * поправка предсказывается из входа и задаётся НА ГРУППУ (16 каналов), а не на канал;
#   * маска `(t mod блок) >= tap` не пускает свёртку за начало блока -- блоки независимы, и
#     именно это позволяет считать блок за ОДИН проход.
#
# Формула: y[t] = (base[0,c] + d[t,0,g]) * x[t] + (base[1,c] + d[t,1,g]) * x[t-1] * [t mod B >= 1]
#
# ЗАЧЕМ СВОЯ, А НЕ ЧУЖАЯ: тело черновика идёт в горячий путь, и владеть им надо целиком --
# иначе стык снова окажется чужим ([[fa2-sm70-vladenie-stykom]]). Здесь же видно, что цена
# операции мизерная: одно умножение на группу плюс умножение-сложение на канал, БЕЗ обращения к
# длинному контексту. На Volta ложится тривиально.
# ================================================================================================
from __future__ import annotations

import torch


def свёртка_по_группам(
    вход: torch.Tensor,        # [T, скрытая]
    дельта: torch.Tensor,      # [T, тактов, групп]  -- поправка на ГРУППУ
    база: torch.Tensor,        # [тактов, скрытая]   -- базовое ядро на КАНАЛ
    блок: int,
    групп: int,
    размер_группы: int,
    тактов: int,
) -> torch.Tensor:
    """Одно применение свёртки. Возвращает [T, скрытая]."""
    по_группам = вход.unflatten(-1, (групп, размер_группы))              # [T, G, S]
    коэф = база.view(1, тактов, групп, размер_группы) + дельта.unsqueeze(-1)
    выход = коэф[:, 0] * по_группам
    # Позиция ВНУТРИ блока: для степени двойки маска дешевле остатка.
    поз = torch.arange(вход.shape[0], device=вход.device)
    поз = (поз & (блок - 1)) if (блок & (блок - 1)) == 0 else (поз % блок)
    for такт in range(1, тактов):
        сдвиг = torch.nn.functional.pad(по_группам[:-такт], (0, 0, 0, 0, такт, 0))
        выход = выход + коэф[:, такт] * сдвиг * (поз >= такт).view(-1, 1, 1)
    return выход.flatten(-2)
