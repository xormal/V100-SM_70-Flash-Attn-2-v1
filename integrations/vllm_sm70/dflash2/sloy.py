# ПОРЯДОК ОПЕРАЦИЙ (снят с эталона, не угадан):
#     норма(вход, остаток)
#     свёртка.подготовить -> ВНИМАНИЕ -> свёртка.завершить
#     норма_после_внимания(вход, остаток)
#     свёртка.подготовить -> MLP -> свёртка.завершить
# То есть свёртка ОБРАМЛЯЕТ и внимание, и MLP: `prepare` до, `finish` после. Отсюда «двухтактная»
# -- два ПРИМЕНЕНИЯ за проход через блок, а не два отсчёта (см. RECEPT §13).
#
# ЧТО ЗДЕСЬ НАШЕ, А ЧТО ВЗЯТО ФОРМОЙ. Формулы и порядок -- как у авторов (иначе веса не подойдут,
# а гейт тождества не пройдёт). НАШЕ -- исполнение: внимание пойдёт нашим ядром со скользящим
# окном (левая граница у него уже параметром) и с ДВУНАПРАВЛЕННОЙ маской внутри блока, чего
# upstream не может при квантованном KV, а мы можем -- бэкенд наш.
# ================================================================================================
from __future__ import annotations

import torch

from .svertka import свёртка_по_группам


def норма_rms(x: torch.Tensor, вес: torch.Tensor, eps: float) -> torch.Tensor:
    """RMS-норма в fp32 -- накопление в половинной точности здесь даёт дрейф на длинном блоке."""
    т = x.float()
    т = т * torch.rsqrt(т.pow(2).mean(-1, keepdim=True) + eps)
    return (т * вес.float()).to(x.dtype)


class ПараСвёрток:
    """Одна свёртка слоя: обе стороны сразу, коэффициенты считаются ОДНИМ умножением.

    Проекция выдаёт 1280 = 2 стороны x 2 такта x 320 групп. `подготовить` берёт свою половину и
    ОТДАЁТ вторую -- её же потом получает `завершить`. Так второе умножение не нужно.
    """

    def __init__(self, база: torch.Tensor, проекция: torch.Tensor, блок: int,
                 групп: int, размер_группы: int, тактов: int):
        self.база, self.проекция = база, проекция
        self.блок, self.групп, self.размер_группы, self.тактов = блок, групп, размер_группы, тактов

    def подготовить(self, x: torch.Tensor):
        коэф = (x @ self.проекция.T).reshape(-1, 2, self.тактов, self.групп)
        y = свёртка_по_группам(x, коэф[:, 0], self.база[0], self.блок,
                               self.групп, self.размер_группы, self.тактов)
        return y, коэф[:, 1]

    def завершить(self, x: torch.Tensor, коэф: torch.Tensor) -> torch.Tensor:
        return свёртка_по_группам(x, коэф, self.база[1], self.блок,
                                  self.групп, self.размер_группы, self.тактов)


def мlp(x: torch.Tensor, gate: torch.Tensor, up: torch.Tensor, down: torch.Tensor) -> torch.Tensor:
    return (torch.nn.functional.silu(x @ gate.T) * (x @ up.T)) @ down.T


def внимание_черновика(
    x: torch.Tensor,               # [T, скрытая]
    wq: torch.Tensor, wk: torch.Tensor, wv: torch.Tensor, wo: torch.Tensor,
    q_норма: torch.Tensor, k_норма: torch.Tensor,
    позиции: torch.Tensor,         # [T]
    голов: int, kv_голов: int, размер_головы: int,
    окно: int, блок: int, eps: float,
    косинус: torch.Tensor, синус: torch.Tensor,   # [T, размер_головы/2]
    kv_внеш=None,                  # ([S,nkv,hd], [S,nkv,hd], [S]) -- ВПРЫСНУТЫЙ контекст
) -> torch.Tensor:
    """Внимание черновика: GQA 32/8, нормировка ПО ГОЛОВЕ, скользящее окно, блок ДВУНАПРАВЛЕННЫЙ.

    ДВЕ ОСОБЕННОСТИ, ради которых это тело наше:
      * ВНУТРИ блока маска ДВУСТОРОННЯЯ -- маскированные позиции видят друг друга, иначе блочная
        выдача теряет смысл (upstream не может так при квантованном KV: бэкенды отвергают
        non-causal вместе с fp8/int8; у нас бэкенд свой, а в ядре `causal` -- параметр);
      * СКОЛЬЗЯЩЕЕ ОКНО {окно}: за его пределы черновик не смотрит, поэтому его цена НЕ РАСТЁТ
        с длиной контекста -- ровно то, чего требовала наша диагностика декода.
    Здесь эталонная запись на общих операциях; на наше ядро переводится подстановкой вызова,
    потому что и окно (левая граница), и признак причинности у него уже параметрами.
    """
    T = x.shape[0]
    q = (x @ wq.T).view(T, голов, размер_головы)
    k = (x @ wk.T).view(T, kv_голов, размер_головы)
    v = (x @ wv.T).view(T, kv_голов, размер_головы)
    # Нормировка ПО ГОЛОВЕ (вес длины размер_головы), а не по скрытой -- это видно из форм весов.
    q = норма_rms(q, q_норма, eps)
    k = норма_rms(k, k_норма, eps)

    def повернуть(t):
        # NEOX (половинами), как у цели -- см. пояснение в telo_polnoe.kv_контекста.
        c, s = косинус.unsqueeze(1), синус.unsqueeze(1)
        л, пр = t[..., :t.shape[-1] // 2], t[..., t.shape[-1] // 2:]
        return torch.cat((л * c - пр * s, л * s + пр * c), dim=-1)

    q, k = повернуть(q), повернуть(k)
    повтор = голов // kv_голов
    k = k.repeat_interleave(повтор, dim=1)
    v = v.repeat_interleave(повтор, dim=1)

    # [СШИВКА ВПРЫСКА С ПРОХОДОМ БЛОКА -- 01.09, для дообучения черновика]
    # В выводе черновик НЕ прогоняет контекст: его K/V впрыскиваются из признаков цели
    # (`kv_контекста`). Эталон же считал K/V из своего ряда, поэтому обучать на нём было
    # нельзя -- обучение шло бы не по той задаче, что решается в бою. Здесь контекст
    # подаётся ГОТОВЫМ и просто дописывается слева; при `kv_внеш=None` поведение прежнее
    # ДО БИТА, поэтому гейты эталона не трогаются.
    поз_блока = позиции
    if kv_внеш is not None:
        k_вн, v_вн, поз_вн = kv_внеш
        k_вн = k_вн.repeat_interleave(повтор, dim=1) if k_вн.shape[1] == kv_голов else k_вн
        v_вн = v_вн.repeat_interleave(повтор, dim=1) if v_вн.shape[1] == kv_голов else v_вн
        k = torch.cat([k_вн.to(k.dtype), k], dim=0)
        v = torch.cat([v_вн.to(v.dtype), v], dim=0)
        поз_блока = torch.cat([поз_вн.to(позиции.dtype), позиции], dim=0)
    оценки = torch.einsum("thd,shd->hts", q, k) / (размер_головы ** 0.5)
    # МАСКА: за окно не смотрим; ВНУТРИ своего блока -- видим всё (двусторонне), вне блока -- только назад.
    поз_i = позиции.view(-1, 1)
    поз_j = поз_блока.view(1, -1)
    # [ДВУСТОРОННОСТЬ КАК В БОЮ -- 08.09] Бой объявляет ЗАПРОСНУЮ часть непричинной целиком
    # (`причинный = not dflash_has_any_non_causal`, у нас is_causal=false), то есть все k
    # позиций видят друг друга независимо от того, кратна ли их первая позиция размеру блока.
    # Здесь же группировка шла по `поз // блок`: при непарной первой позиции блок РАЗРЕЗАЛСЯ
    # границей, и половина запроса теряла соседей. Прежнее правило сохранено для пути без
    # впрыска -- там гейты эталона считаны на нём.
    if kv_внеш is not None:
        _зпр = torch.zeros_like(поз_блока, dtype=torch.bool)
        _зпр[-T:] = True
        один_блок = _зпр.view(1, -1).expand(T, -1)
    else:
        один_блок = (поз_i // блок) == (поз_j // блок)
    видно = ((поз_j <= поз_i) | один_блок) & ((поз_i - поз_j) < окно)
    оценки = оценки.masked_fill(~видно.unsqueeze(0), float("-inf"))
    вес = torch.softmax(оценки.float(), dim=-1).to(x.dtype)
    выход = torch.einsum("hts,shd->thd", вес, v).reshape(T, голов * размер_головы)
    return выход @ wo.T
