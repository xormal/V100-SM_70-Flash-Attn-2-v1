# ЗАЧЕМ ОН ВООБЩЕ ЕСТЬ. Черновик выдаёт k позиций ЗА ОДИН проход, то есть позиции считаются
# ПАРАЛЛЕЛЬНО и ничего не знают о том, что выбрано у соседа. Взять поточечный argmax -- значит
# склеить k независимых догадок, которые между собой не связаны: «I like|like to|to go» ломается на
# первой же паре. Отбор чинит ровно это -- и чинит ДЁШЕВО, не вторым проходом тела.
#
# УСТРОЙСТВО (снято с эталона, не из статьи):
#   на каждой позиции l берутся top_k=16 кандидатов от общего lm_head (унарная часть),
#   а связь пары (предшественник p на l-1, преемник c на l) оценивается НИЗКОРАНГОВОЙ формой:
#
#       ребро[l, p, c] = унарная[l, c] + < кодбук_пред[id_p] * H[l], кодбук_прее[id_c] >
#
#   где H[l] = проекция скрытого состояния в ранг r=256. То есть таблица переходов не хранится
#   (это было бы 248320^2), а СОБИРАЕТСЯ из двух словарей ранга 256 -- 2*248320*256 весов.
#   Позиция 0 связывается с ЯКОРЕМ -- уже принятым токеном, поэтому путь пришит к реальности.
#
#   Далее по цепи ищется ЛУЧШИЙ ПУТЬ (Виттерби): k*K*K = 8*16*16 = 2048 сложений на запрос.
#   Это не эвристика и не пучок -- это ТОЧНЫЙ максимум суммы рёбер, потому что граф -- цепь.
#
# ПОЧЕМУ ЭТО НАШ КЛАСС ЗАДАЧИ. Форма «низкий ранг вместо большой таблицы» -- ровно тот ход, который
# в нашем пакете зовётся перепараметризацией: объект не «матрица переходов», а «две таблицы ранга
# 256», и тогда стоимость падает с V^2 до V*r. Считать это на карте нечем не надо -- обе половины
# суть умножения, а цепь короткая.
#
# ГЕЙТ ЭТОГО ФАЙЛА (внизу): собранная форма побитово равна прямому двойному циклу, а Виттерби
# совпадает с ПОЛНЫМ перебором K^k путей. Пока не совпало -- тело писать рано.
# ================================================================================================
from __future__ import annotations

import torch


def оценить_рёбра(
    кодбук_пред: torch.Tensor,     # [V, r]
    кодбук_прее: torch.Tensor,     # [V, r]
    кандидаты: torch.Tensor,       # [B, L, K] -- id top_k на каждой позиции
    унарные: torch.Tensor,         # [B, L, K] -- их же логиты от lm_head
    скрытое_r: torch.Tensor,       # [B, L, r] -- проекция скрытого в ранг
    якорь: torch.Tensor,           # [B]       -- уже принятый токен (предшественник позиции 0)
) -> torch.Tensor:
    """[B, L, K_пред, K_прее]: цена перехода в кандидата c при предшественнике p.

    Позиция 0 -- особая: у неё единственный предшественник (якорь), поэтому его id размножается
    по оси p. Так путь начинается НЕ с догадки, а с факта.
    """
    B, L, K = кандидаты.shape
    преемники = кодбук_прее[кандидаты]                       # [B, L, K, r]
    id_пред = torch.cat(
        (якорь[:, None, None].expand(-1, 1, K), кандидаты[:, :-1]), dim=1
    )                                                        # [B, L, K]
    предшественники = кодбук_пред[id_пред]                   # [B, L, K, r]
    # Скрытое входит МЕЖДУ словарями (модулирует предшественника) -- это и делает форму
    # зависимой от контекста, а не статической таблицей биграмм.
    return унарные[:, :, None] + torch.einsum(
        "blpr,blcr->blpc", предшественники * скрытое_r[:, :, None], преемники
    )


def витерби(рёбра: torch.Tensor) -> torch.Tensor:
    """Точный лучший путь по цепи. [B, L, K, K] -> [B, L] (индексы кандидатов).

    Цепь -- значит динамика по одной оси: лучший путь в c на шаге l зависит только от лучших
    путей в p на шаге l-1. Перебор K^L не нужен, и приближение тоже: максимум ТОЧНЫЙ.
    """
    B, L, K, _ = рёбра.shape
    # Позиция 0: все p -- один и тот же якорь, берём строку 0.
    цена = рёбра[:, 0, 0, :]                                  # [B, K]
    откуда = torch.zeros(B, L, K, dtype=torch.long, device=рёбра.device)
    for l in range(1, L):
        полная = цена[:, :, None] + рёбра[:, l]                # [B, K_пред, K_прее]
        цена, лучший_p = полная.max(dim=1)                     # [B, K]
        откуда[:, l] = лучший_p
    путь = torch.zeros(B, L, dtype=torch.long, device=рёбра.device)
    текущий = цена.argmax(dim=1)                               # [B]
    for l in range(L - 1, -1, -1):
        путь[:, l] = текущий
        текущий = откуда[:, l].gather(1, текущий[:, None]).squeeze(1)
    return путь


def отобрать(
    кодбук_пред, кодбук_прее, кандидаты, унарные, скрытое_r, якорь
) -> torch.Tensor:
    """Готовые k токенов черновика: [B, L] id из словаря."""
    рёбра = оценить_рёбра(кодбук_пред, кодбук_прее, кандидаты, унарные, скрытое_r, якорь)
    путь = витерби(рёбра)
    return кандидаты.gather(2, путь[:, :, None]).squeeze(2)


# ==================================================================================================
# ОТБОР ПО ОЖИДАЕМОЙ ДЛИНЕ ПРЕФИКСА (консультация Fable, 25.08). СТРОГО ЛУЧШЕ ВИТТЕРБИ, ДАРОМ.
# ==================================================================================================
# ЧТО НЕ ТАК С ВИТТЕРБИ (он же -- отбор эталонной реализации). Сумма рёбер раскладывается точно:
#
#     W(s) = log П q_l(s_l|s_{l-1}) + Σ_l log Z_l(s_{l-1}),   Z_l(p) = Σ_c exp(ребро[l,p,c])
#
# то есть максимум суммы -- это максимум вероятности того, что совпадут ВСЕ L позиций сразу, да ещё
# с паразитным членом Σ log Z, вознаграждающим предшественников, у которых велика масса следующей
# позиции (к согласию отношения не имеет). А платят нам НЕ за полное совпадение: приёмка обрывается
# на первом расхождении, и ценность цепочки -- ДЛИНА СОВПАВШЕГО НАЧАЛА:
#
#     E[R(s)] = Σ_{m=1..L} П_{l<=m} q_l(s_l | s_{l-1})
#
# Эти два максимума РАЗЛИЧАЮТСЯ уже при L=K=2, и разрыв неограничен (контрпример Fable: MAP берёт
# цепочку с E[R]=0.780 против оптимума 0.944). Наш замер показал ровно этот почерк: приёмка позиции
# 1 (41 % условных) ХУЖЕ позиции 2 (55 %) -- отбор жертвовал ранними ради поздних.
#
# ТОЧНЫЙ АЛГОРИТМ. Сумма префиксных произведений сворачивается по Горнеру:
#     E[R] = q_1(1 + q_2(1 + q_3(1 + ...)))
# откуда обратная динамика ОДНИМ числом на узел:
#     G_l(p) = max_c q_l(c|p) * (1 + G_{l+1}(c)),   G_{L+1} = 0.
# Никакого фронта Парето не нужно: множитель хвоста -- одно число, а q>0, значит выбор хвоста
# масштабно-инвариантен. Сложность O(L*K^2) -- ТА ЖЕ, что у Виттерби.
# ==================================================================================================


def отобрать_по_префиксу(
    кодбук_пред: torch.Tensor,
    кодбук_прее: torch.Tensor,
    кандидаты: torch.Tensor,       # [B, L, K]
    унарные: torch.Tensor,         # [B, L, K]
    скрытое_r: torch.Tensor,       # [B, L, r]
    якорь: torch.Tensor,           # [B]
) -> torch.Tensor:
    """[B, L] токенов черновика, максимизирующих ОЖИДАЕМУЮ длину принятого начала."""
    рёбра = оценить_рёбра(кодбук_пред, кодбук_прее, кандидаты, унарные, скрытое_r, якорь)
    путь = динамика_префикса(рёбра)
    return кандидаты.gather(2, путь[:, :, None]).squeeze(2)


def динамика_префикса(рёбра: torch.Tensor) -> torch.Tensor:
    """[B,L,K,K] -> [B,L]. Обратная динамика Горнера; нормировка ПО ПРЕДШЕСТВЕННИКУ обязательна.

    Нормировка (вычитание log Z_l(p)) -- не косметика: именно она убирает паразитный член суммы
    рёбер. Считается тем же проходом, лишних чтений нет.
    """
    B, L, K, _ = рёбра.shape
    log_q = рёбра - торч_логсумма(рёбра)
    q = log_q.exp()
    G = torch.zeros(B, K, dtype=q.dtype, device=q.device)      # G_{L+1} = 0
    выбор = torch.zeros(B, L, K, dtype=torch.long, device=q.device)
    for l in range(L - 1, -1, -1):
        значение = q[:, l] * (1.0 + G[:, None, :])             # [B, K_пред, K_прее]
        G, лучший = значение.max(dim=-1)                        # [B, K_пред]
        выбор[:, l] = лучший
    путь = torch.zeros(B, L, dtype=torch.long, device=q.device)
    # У позиции 0 предшественник ЕДИНСТВЕННЫЙ (якорь) -- все строки p одинаковы, берём нулевую.
    предш = torch.zeros(B, 1, dtype=torch.long, device=q.device)
    for l in range(L):
        c = выбор[:, l].gather(1, предш)
        путь[:, l] = c.squeeze(1)
        предш = c
    return путь


def торч_логсумма(x: torch.Tensor) -> torch.Tensor:
    return x.logsumexp(dim=-1, keepdim=True)
