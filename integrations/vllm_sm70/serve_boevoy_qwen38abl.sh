#!/usr/bin/env bash
# БОЕВОЙ ПУСК: Qwen3.8-27B-ABLITERATED, int8(GPTQ) + i12 на внимании, наши ядра, карты 2-3.
#
# ЧТО ЭТО ТАКОЕ. Не «ещё один вариант запуска», а ЗАКРЕПЛЁННАЯ точка: каждый параметр здесь либо
# ЗАМЕРЕН, либо унаследован от прежнего боевого намеренно. Скрипт -- тонкая обёртка над
# `serve_qwen38_int8.sh`, а не его копия: у нас уже был случай, когда второй экземпляр логики
# подъёма разошёлся с первым и месяцами жил своей жизнью. Одно тело, все различия -- здесь и явно.
#
# ПОЧЕМУ КАЖДЫЙ ПИН ИМЕННО ТАКОЙ (17.08.2026, всё замерено на этой же сети):
#
#   KV 6 ГиБ            Честная ёмкость 1.44 x 262144 = 377 487 токенов; 250K проверены
#                       поведением (249 847 токенов, игла у позиции ~30 найдена). БОЛЬШЕ НЕ СТАВИТЬ:
#                       пул закреплён отдельно, и его рост отнимает запас у АКТИВАЦИЙ -- при 12 ГиБ
#                       тот же 250K-запрос падает с "Tried to allocate 54.00 MiB". Строку
#                       "GPU KV cache size: N tokens" в логе ЧИТАТЬ НЕЛЬЗЯ, она врёт на гибридных
#                       сетях; честная -- следующая, "Maximum concurrency ... Xx".
#   чанк 4096           Пик префилла вчетверо ниже, чем при 16384. Именно он убивал движок на
#                       длинных промптах. На подъём не влияет вовсе (при заданном
#                       --kv-cache-memory-bytes профилирование ПРОПУСКАЕТСЯ).
#   max_num_seqs 4      Унаследовано; 8 не поднимается (записано в слепке про 512K).
#   W8=1 LMH=1 FMLP=1   Линейная часть, словарная проекция и хвост слоя -- наши. Проверено на этой
#                       сети: инструменты, 5 ступеней конкурентности до 2x246K, отказов ноль.
#   W12=1 EXCH12=1      Умолчания режима dialog; W12 обязателен -- слепок НАМЕРЕННО оставил
#   KV_I8=1             self_attn.{q,k,v}_proj плотными, их берёт на себя этот рычаг.
#   имена модели        ПЕРВЫЕ ДВА ИМЕНИ МЕНЯТЬ НЕЛЬЗЯ: под ними ходят живые клиенты нынешнего
#                       боевого. Настоящее имя добавлено третьим.
#   enable_thinking     false -- КАК СЕЙЧАС У БОЕВОГО (рычаг FA2SM70_THINK=true). Сеть думающая и с true тоже верна, но смена
#                       этого флага меняет ФОРМУ ответа клиентам; включать отдельным решением
#                       (FA2SM70_THINK=1), а не заодно с переездом.
#   tool-call-parser    qwen3_coder -- ЗАМЕРЕН на этой сети (вызов верен, аргументы разбираются).
#                       У прежнего боевого стоит hermes, но там ДРУГАЯ сеть и другой шаблон чата.
#   шаблон чата         СВОЙ, из слепка. Шаблон от Qwen3.6 сюда не подходит.
#   каталог сборки      ОТДЕЛЬНЫЙ. Собирать в тот, из которого работает живой сервер, нельзя:
#                       подмена .so на месте роняет его (записано, проверено болью).
#
# ПОРЯДОК ПЕРЕЕЗДА -- в PLAN_PEREEZDA.md рядом. Коротко: обкатать этим же скриптом на 8090,
# затем promote_to_prod.sh --verified, затем погасить 8085 по PID и поднять этот скрипт.
#
# Использование:
#   ./serve_boevoy_qwen38abl.sh                 # БОЕВОЙ: карты 2-3, порт 8085
#   PORT=8090 CARDS=0,1 ./serve_boevoy_qwen38abl.sh   # обкатка, боевого не трогает
#   ./serve_boevoy_qwen38abl.sh --check         # только проверить готовность, не запускать
set -uo pipefail

RUNDIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
BASE="$RUNDIR/serve_qwen38_int8.sh"
MODELDIR="${MODEL:-/mnt/d1/alex/VLLM_ch/Qwen3.8-27B-ABL_int8_i12}"

PORT="${PORT:-8085}"
# [КАРТЫ: UUID -> ЦЕЛЫЙ ИНДЕКС СРЕДИ ЖИВЫХ -- 11.09, авария карты 0]
# В 08:20:47 карта 0 отвалилась от шины. Боевой процесс выжил, но ПЕРЕЗАПУСК бы провалился: CUDA
# перечисляет только живые устройства, и `CUDA_VISIBLE_DEVICES=2,3` дало ОДНУ карту вместо двух
# (проверено). Первая правка -- передать UUID прямо в CUDA_VISIBLE_DEVICES -- оказалась МИНОЙ:
# vLLM делает int() над его элементами (platforms/interface.py:214, device_id_to_physical_device_id)
# и воркер не импортируется. Проверено полным импортом `vllm.v1.worker.gpu_model_runner`.
# Поэтому: UUID разрешаются в ЦЕЛЫЕ индексы на момент запуска. При CUDA_DEVICE_ORDER=PCI_BUS_ID
# (стоит в базовом пускаче) индекс CUDA равен позиции карты в списке ЖИВЫХ по шине -- ровно то,
# что печатает nvidia-smi по умолчанию. Если UUID не найден -- откат на $CARDS с предупреждением.
_UUID_KARTA2="GPU-ee8e25ee-82ab-22b3-1486-87ecef3ec8ef"
_UUID_KARTA3="GPU-cf51dbe3-0526-6898-c69d-943b21e24895"
CARDS="${CARDS:-2,3}"
_zhivye="$(nvidia-smi --query-gpu=uuid --format=csv,noheader 2>/dev/null | tr -d ' ')"
_i2=$(printf '%s\n' "$_zhivye" | grep -n -x "$_UUID_KARTA2" | cut -d: -f1)
_i3=$(printf '%s\n' "$_zhivye" | grep -n -x "$_UUID_KARTA3" | cut -d: -f1)
if [ -n "$_i2" ] && [ -n "$_i3" ]; then
  export FA2SM70_CVD="${FA2SM70_CVD:-$((_i2-1)),$((_i3-1))}"
else
  export FA2SM70_CVD="${FA2SM70_CVD:-$CARDS}"
  echo "[боевой] ВНИМАНИЕ: UUID боевых карт не найдены среди живых ($(printf '%s' "$_zhivye" | tr '\n' ' ')) -- беру CARDS=$CARDS" >&2
fi

say() { printf '[боевой] %s\n' "$*"; }
die() { printf '[боевой] ОТКАЗ: %s\n' "$*" >&2; exit 1; }

# ------------------------------------------------------------------ проверки готовности
[ -x "$BASE" ] || [ -f "$BASE" ] || die "нет базового пускача $BASE"
[ -d "$MODELDIR" ] || die "нет слепка $MODELDIR"
[ -f "$MODELDIR/model.safetensors.index.json" ] || die "слепок неполон: нет индекса весов"

# СЛЕПОК ОБЯЗАН НЕСТИ ОБА ПОЛЯ. Без modules_to_not_convert и без dynamic по СЛИТЫМ именам
# (qkv_proj, in_proj_ba) плотные модули строятся как квантованные: сервер ПОДНИМАЕТСЯ, ОБСЛУЖИВАЕТ
# и выдаёт "!!!!!!". Это стоило одного подъёма 17.08; проверка ставится здесь, чтобы не стоило второго.
python3 - "$MODELDIR" <<'PY' || die "config.json слепка не годен (см. выше)"
import json, sys
q = json.load(open(sys.argv[1] + "/config.json")).get("quantization_config") or {}
беды = []
if not q.get("modules_to_not_convert"):
    беды.append("нет modules_to_not_convert")
d = " ".join(q.get("dynamic") or {})
if "qkv_proj" not in d:
    беды.append("dynamic без qkv_proj (шаблоны по несплавленным именам -- промах)")
if "in_proj_ba" not in d:
    беды.append("dynamic без in_proj_ba")
if q.get("bits") != 8 or q.get("group_size") != 128:
    беды.append(f"ожидались 8 бит / группа 128, а там {q.get('bits')}/{q.get('group_size')}")
print("[боевой] слепок: " + ("ГОДЕН" if not беды else "НЕ ГОДЕН -- " + "; ".join(беды)))
sys.exit(1 if беды else 0)
PY

# СУХОЙ ПРОГОН (FA2SM70_DRYRUN=1) НЕ ТРОГАЕТ НИЧЕГО: ни занятости карт, ни замков, ни
# осиротевших процессов. Он отвечает на один вопрос -- какую конфигурацию даст скрипт САМ.
if [ "${FA2SM70_DRYRUN:-0}" = "1" ]; then
  say "СУХОЙ ПРОГОН: защита от столкновения и уборка замков пропущены"
else
# ЗАЩИТА ОТ СТОЛКНОВЕНИЯ С ЖИВЫМ СЕРВЕРОМ. Порядок опознания только снизу: PID -> uuid -> НОМЕР
# карты. Имена процессов и шаблоны здесь не годятся -- по шаблону уже роняли боевой трижды.
busy=""
while IFS=, read -r pid uuid; do
  pid="${pid// /}"; uuid="${uuid// /}"
  idx=$(nvidia-smi --query-gpu=index,uuid --format=csv,noheader | grep -F "$uuid" | cut -d, -f1 | tr -d ' ')
  case ",$CARDS," in *",$idx,"*) busy="$busy $idx(pid=$pid)" ;; esac
done < <(nvidia-smi --query-compute-apps=pid,gpu_uuid --format=csv,noheader)
if [ -n "$busy" ]; then
  say "карты $CARDS ЗАНЯТЫ:$busy"
  [ "${FA2SM70_PROD_FORCE:-0}" = "1" ] || die "сперва погасить занявшего (по PID, снизу от nvidia-smi), либо FA2SM70_PROD_FORCE=1"
  say "FA2SM70_PROD_FORCE=1 -- продолжаю поверх занятых карт (так делать не следует)"
fi

# ЗАТИРАНИЕ ЗАЛИПШИХ ЗАМКОВ ПЕРЕД ПОДЪЁМОМ.
# Порядок и есть защита: сперва спрашиваем ПОРТ. Если там кто-то отвечает 200 -- он живой,
# и мы выходим, ничего не тронув. Всё, что осталось после этой проверки, -- мусор:
#   * flock `.serve_<порт>.lock`, который 17.08 держали осиротевшие обёртка и `tee`
#     (карты уже свободны, а подъём отказывает -- боевой лежал зря);
#   * сборочные замки torch, вешающие следующий подъём наглухо и без ошибки;
#   * сами осиротевшие процессы цепочки на нашем порту.
# После сбоя питания PID из старых файлов могут быть ПЕРЕВЫДАНЫ чужим процессам, поэтому
# опознание идёт по СТРОКЕ ЗАПУСКА, а не по факту «PID жив».
_code=$(curl -s -o /dev/null -w '%{http_code}' -m 4 "http://127.0.0.1:$PORT/v1/models" 2>/dev/null)
if [ "$_code" = "200" ]; then
  say "порт $PORT уже отвечает 200 -- живой сервер, ничего не трогаю"
else
  _n=0
  for _p in $(ps -eo pid= 2>/dev/null); do
    [ -r "/proc/$_p/cmdline" ] || continue
    _full=$(tr '\0' ' ' < "/proc/$_p/cmdline" 2>/dev/null) || continue
    case "$_full" in
      *"--port $PORT"*|*"tee "*"serve_${PORT}_"*)
        say "снимаю осиротевший pid=$_p"; kill -9 "$_p" 2>/dev/null; _n=$((_n+1)) ;;
    esac
  done
  [ "$_n" -gt 0 ] && sleep 3
  rm -f "$RUNDIR/.serve_${PORT}.lock" && say "замок порта снят"
  for _L in $(find "${FA2SM70_BUILD_DIR:-$RUNDIR/.fa2sm70_build_prod38abl}" \
              "$HOME/.cache/torch_extensions" -name "lock" 2>/dev/null); do
    rm -f "$_L" && say "снят сборочный замок $_L"
  done
fi

fi

if [ "${1:-}" = "--check" ]; then
  say "проверка готовности пройдена: слепок годен, карты $CARDS, порт $PORT"
  exit 0
fi

# ------------------------------------------------------------------ ЗАКРЕПЛЁННЫЕ ПАРАМЕТРЫ
export MODEL="$MODELDIR"
export CARDS PORT
# ПОЛНЫЙ CUDA-ГРАФ ДЕКОДА -- НА БОЕВОЙ СЕТИ ВЫКЛЮЧЕН, И ЭТО ЗАМЕРЕНО ОТКАЗОМ.
#
# На СТЕНДЕ (Qwen3.8-27B int8, карты 0-1) рычаг даёт декод x1.084-1.091 и поднимается чисто --
# поэтому 21.08 он был врезан сюда со значением 1. Это была ОШИБКА ПЕРЕНОСА: на боевой сети
# (ABLITERATED, карты 2-3) подъём ПАДАЕТ при захвате графа:
#     RuntimeError: Triton Error [CUDA]: operation failed due to a previous error during capture
#     torch.AcceleratorError: CUDA error ... cudaErrorStreamCaptureInvalidated
# То есть внутрь захвата попадает Triton-тело, которое захват не переживает. Пойман 21.08 при
# первом же перезапуске боевого; до этого боевой ХОДИЛ СО СТАРЫМ ОКРУЖЕНИЕМ (переменной не было),
# и правка не проверялась ни разу -- «сделано» опять оказалось не равно «работает».
#
# ВКЛЮЧАТЬ ТОЛЬКО ПОСЛЕ того, как найдено и снято Triton-тело в захвате, и подъём боевого пройден
# целиком. Стенда для этого НЕ ДОСТАТОЧНО: сети разные, и падает именно боевая.
# [26.08] ПОЛНЫЙ ГРАФ ВКЛЮЧЁН. Он стоял в 0 из-за мины «CG=1 не поднимает боевую сеть»
# (cudaErrorStreamCaptureInvalidated в Triton-теле). Мина была СЛЕДСТВИЕМ отката рекуррента
# GDN на Triton, а откат -- следствием несобранного расширения (см. §55: rsync сохранил
# времена). Откат устранён, и тот же слепок на стенде с графом идёт 48.1/45.7/40.5 ток/с
# против 33.6/26.6/21.6 без графа. Если подъём с графом когда-нибудь снова упадёт --
# FA2SM70_CG=0 возвращает прежнее поведение одной переменной.
# [29.08] ПОЛНЫЙ ГРАФ СНЯТ ПО ПРАВИЛЬНОСТИ, А НЕ ПО СКОРОСТИ.
# Замер с ЖЁСТКИМ оракулом (черновик из нулей обязан отвергаться целиком, значит выдача
# обязана совпасть с безспекулятивной):
#     как в бою (CG=1)     -- совпало с эталоном 0/4, различных 4/4
#     FA2SM70_CG=0         -- совпало 4/4, различных 1/4
#     без qGrp, CG=1       -- совпало 0/4  (то есть дело НЕ в группировке позиций)
# То есть боевой на коротких запросах выдавал НЕ жадный ответ цели: ' Столица: Мадрид',
# ' Столица: Тбилиси', китайский текст -- вместо ' Париж...'. Это же объясняет раздел
# 8-кватер протокола падений (12 одинаковых запросов -> 8 разных ответов).
# Цена снятия -- те самые 9 % декода, что граф давал 26.08. Правильность дороже.
# [31.08] ЗАПРЕТ СНЯТ ЗАМЕРОМ, НО РЫЧАГ ОСТАЁТСЯ ВЫКЛЮЧЕННЫМ.
# Прежний оракул перепроверен на восьми запросах и ЧЕТЫРЁХ запусках (база, база, граф, граф).
# Сравнение «граф против базы» дало 6/8 -- но контроль возвратом к базе дал 5/8: та же самая
# конфигурация с собой расходится сильнее, чем конфигурации между собой. Повтор прибора В ТОМ
# ЖЕ сервере -- 8/8 побайтово, значит недетерминизм строго межзапусковый (тюнинг выключен,
# блоков KV поровну 90 112). Годное ядро прибора -- пять устойчивых запросов, и на них граф
# совпал с базой во всех четырёх запусках. Дефект 29.08 сидел ровно там (' Столица: Мадрид'),
# и сегодня НЕ воспроизводится.
# Скорость на 5.9K: CG=0 медиана 37.79 мс/ток, CG=1 медиана 36.50 -- разница 3.4 % при
# разбросе ±10 %, то есть в пределах шума. Прежних x1.43-1.88 больше нет: путь ускорился
# телом и снятыми метаданными, доля накладных запуска упала. Замер шёл под боевым, потому
# это НИЖНЯЯ оценка. Включать в бой незачем -- приза не видно; см. записку 25 §56.
# [29.08] СВОЙ ALL-REDUCE vLLM: ОГРАНИЧЕНИЕ ОТПАЛО ВМЕСТЕ С ГРАФОМ.
# Опись шага декода по ядрам (профиль 29.08, 25 шагов, только декод) назвала обмен третьей
# фазой: NCCL 7.31 мс из ~39 мс ядерного времени (19 %). Это 128 коллективов по 10 КиБ за
# шаг, то есть ЧИСТАЯ ЛАТЕНТНОСТЬ, а не полоса -- ровно тот случай, ради которого у vLLM
# есть свой одношаговый all-reduce. Он был запрещён безусловно; проверяется замером.
# ПОЧЕМУ ОН БЫЛ ЗАПРЕЩЁН (запись в serve_qwen38_int8.sh:600): `cudaIpcGetMemHandle` не
# работает на буферах ГРАФОВОГО ПУЛА, поэтому выбор стоял «либо полный граф (+8.4-9.1 %),
# либо свой all-reduce», и граф выигрывал. Граф снят 29.08 по правильности -- значит
# ограничение отпало, и рычаг надо перемерить. Включается FA2SM70_CUSTOM_AR=1.

# [01.09] РАССЫЛКА-СО-СВЕДЕНИЕМ, ПЕРЕКРЫТАЯ С УМНОЖЕНИЕМ -- ВКЛЮЧЕНА.
# Пункт 6 цели буквально: чужая половина строк o_proj/down_proj считается первой и уезжает
# соседу кусками, своя половина служит ей укрытием.
# Гейт на стенде: 8 из 8 запросов ПОБАЙТОВО с базой, включая 26K и 70K. Устойчивость:
# 2042 токена непрерывно, Xid/hang/NCCL WARN -- ноль. Приз +2.8 % медианой шести пар с
# чередованием порядка (A/B ВНУТРИ процесса, записка 25 §70-72). На боевом железе ожидание
# выше: обмен там 17.9 % шага, прячется 20-52 % его.
# Откат -- FA2SM70_AR2=0 одной переменной.
# [01.09] ЗАПИСЬ ВЫХОДА ПРЯМО В БУФЕР ДВИЖКА -- ВЫКЛЮЧЕНА ПО ЗАМЕРУ.
# Правка убирала выделение и копию выхода в общем пути и ПРОХОДИЛА гейт правильности
# (побайтово на 70K). Но на боевом она сделала время нестабильным: с ней наклон гулял
# 26.3-103.5 мс/ток, без неё 24.6-28.8 при базе 27.5. Гейт правильности вреда по ВРЕМЕНИ
# не ловит -- это и есть урок. Причина не выяснена; вероятная -- буфер выхода движка живёт
# асинхронно, и запись прямо в него конфликтует с его жизненным циклом.
# Включать только вместе с замером наклона на боевом в тихом окне. Записка 25 §90.
export FA2SM70_PAGED_OUT="${FA2SM70_PAGED_OUT:-0}"
# [01.09] ОТБОР РАБОТАЕТ И НА ДЕКОДЕ -- ЗАМЕР НА БОЕВОМ, 252 612 ТОКЕНОВ:
#     bez otbora (MINSQ=64): 56.83 / 59.98 ms/tok = 16.7-17.6 tok/s
#     s otborom  (MINSQ=0):  51.84 / 52.00 ms/tok = 19.2-19.3 tok/s   (+11 %)
# Игла найдена в обоих случаях. То есть правка MINSQ=64, введённая утром «чтобы не делать
# лишней работы на декоде», отключала РАБОТАЮЩУЮ разреженность на длинном контексте -- там
