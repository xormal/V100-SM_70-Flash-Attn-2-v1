#   alpha=0.02   gamma=0.5 215.6 с 12/12   <- ВЗЯТО: срез 39 % при полном качестве
# текст L=245272 (плотный 429.9 с, 12/12): alpha=0.005 g=0.5 -> 263.6 с 12/12;
#   alpha=0.01 -> 12/12; alpha=0.02 -> 12/12.
# beta оставлена вентилем (умолчание 0): gamma её перекрывает по замеру.

# [ПОПРАВКА НА РАЗБРОС КЛЮЧЕЙ БЛОКА -- beta]
# ЗАЧЕМ. Счёт блока по СРЕДНЕМУ ключу теряет иглу: у блока, где ключи разбросаны, среднее
# указывает "в никуда", и блок с одним сильно совпадающим ключом получает низкий счёт.
# Доказано 28.08 гейтом тождества: при alpha->0 разреженный путь совпал с плотным ПОБАЙТОВО
# (отпечаток d41ef06464bf9481), значит виновато ПРАВИЛО, а не путь; при 89 % сохранённых
# блоков игла уже терялась. Поправка beta*||q||*(r_J - r̄) поднимает счёт ровно разнородным
# блокам; правит ОТКЛОНЕНИЕ, потому что сырая величина перебивала сигнал в 175 раз.
#
# ЗАМЕР (стенд, текст L=245272, плотный эталон 429.9 с / 12 пар из 12):
#   alpha=0.005 beta=0     346.6 с  11/12      alpha=0.01 beta=0.5  298.0 с  11/12
#   alpha=0.005 beta=0.05  349.2 с  11/12      alpha=0.02 beta=0.5  261.4 с  11/12
#   alpha=0.005 beta=0.2   346.2 с  11/12      alpha=0.02 beta=1.0  232.9 с  10/12
#   alpha=0.005 beta=0.5   365.9 с  12/12  <-- ВЗЯТО
# На трёх текстах beta=0.5 совпадает с плотным или лучше него; на одном отпечаток ответа
# совпал с плотным ПОБАЙТОВО. beta=1.0 ХУЖЕ: слишком большая поправка снова вырождает
# правило в "ранжируй по разбросу".
#
# ЦЕНА: +5.6 % времени префилла против beta=0. Платим её сознательно -- условие владельца
# "без потери точности" не компромисс, а требование, а beta=0 его НЕ выполняет.
# Откат -- FA2SM70_SPARSE_BETA=0 (прежнее правило БИТ В БИТ).
export FA2SM70_SPARSE_BETA="${FA2SM70_SPARSE_BETA:-0}"
export FA2SM70_SPARSE_GAMMA="${FA2SM70_SPARSE_GAMMA:-0.5}"

# [КУСОК ЗОНДОВЫХ СТРОК] 96 = ВЕСЬ набор, то есть БЕЗ разбиения.
# Разбиение на куски (48) даёт занятость 12.5 % -> ~37 % и отбор x1.62, а сквозной префилл
# x1.058, и в микрозамере отбор совпадает ПОБИТОВО. НО замер 28.08 на тексте seed 20260904
# показал: с разбиением теряются ДВЕ иглы, без него -- ОДНА. Сведение по кускам точно
# математически, но порядок сложения иной, и на границе это опрокидывает пограничный блок.
# Скорость, купленная сдвигом на границе, здесь не покупается: условие -- без потери точности.
# Двойная буферизация (x1.18) при этом БИТ В БИТ точна и остаётся включённой всегда.
export FA2SM70_SEL_RC="${FA2SM70_SEL_RC:-96}"

# [РАЗРЕЖЕННОЕ ВНИМАНИЕ ПРЕФИЛЛА -- ДОЛЯ В ПРОЦЕНТАХ, записка 20]
# Удобная единица -- не "порог в токенах", а СКОЛЬКО РАБОТЫ ВНИМАНИЯ считается разреженно.
# Работа внимания растёт как T^2, поэтому доля p работы соответствует порогу T = L*sqrt(1-p):
#     PCT=0 -> порог 262144 (никогда) | PCT=75 -> 131072 | PCT=100 -> 1 (всегда).
# ПОРОГ 0 ЗАРЕЗЕРВИРОВАН ПОД «ВЫКЛЮЧЕНО»: первая редакция отображала 100% в ноль и тем
# ВЫКЛЮЧАЛА ветку ровно там, где просили включить её целиком.
# FA2SM70_SPARSE_T (абсолютный порог) СТАРШЕ: если задан явно, процент не применяется.
# Длина контекста -- переменной, чтобы опыт мог её понизить (например, состояние GDN в fp16
# не влезает в закреплённые 8 ГиБ при 262144: движок отказывает при подъёме).
_MAXLEN=${FA2SM70_MAXLEN:-262144}
if [ -n "${FA2SM70_SPARSE_PCT:-}" ] && [ -z "${FA2SM70_SPARSE_T:-}" ]; then
  FA2SM70_SPARSE_T=$(python3 -c "import math,sys; p=float(sys.argv[1]); print(1 if p>=100 else max(1,int(round($_MAXLEN*math.sqrt(max(0.0,1.0-p/100.0))))))" "$FA2SM70_SPARSE_PCT")
  export FA2SM70_SPARSE_T
  say "разреженное внимание: ${FA2SM70_SPARSE_PCT}% работы -> порог ${FA2SM70_SPARSE_T} токенов, alpha=${FA2SM70_SPARSE_ALPHA:-0.01}"
elif [ -n "${FA2SM70_SPARSE_T:-}" ] && [ "${FA2SM70_SPARSE_T}" != "0" ]; then
  _pct=$(python3 -c "import sys; t=float(sys.argv[1]); print(round(100*(1-(t/$_MAXLEN)**2),1))" "$FA2SM70_SPARSE_T")
  say "разреженное внимание: порог ${FA2SM70_SPARSE_T} токенов -> ${_pct}% работы внимания, alpha=${FA2SM70_SPARSE_ALPHA:-0.01}"
else
  say "разреженное внимание ВЫКЛЮЧЕНО (точный путь на всей длине)"
fi

export FA2SM70_W12="${FA2SM70_W12:-1}"

# [31.08] КЛЮЧ КЭША КОМПИЛЯЦИИ ОБЯЗАН ЗАВИСЕТЬ ОТ РЫЧАГОВ УПАКОВКИ.
# ОТКАЗ, КОТОРЫЙ ЭТО ЛЕЧИТ: подъём падал с `CUDA error: an illegal memory access` (а на
# стенде -- с `AssertionError: wrong number of dimensions` в assert_size_stride inductor'а).
# Причина НЕ в ядрах и НЕ в упаковке: vLLM кладёт скомпилированные графы в
# ~/.cache/vllm/torch_compile_cache/<ключ>, и ключ считается по конфигурации МОДЕЛИ И ДВИЖКА --
# наших переменных в нём нет. А inductor ЗАПЕКАЕТ формы и число измерений аргументов. Слою без
# упаковки мы кладём пустышку (одномерную), упакованному -- настоящий двумерный тензор; значит
# смена FA2SM70_TM8_NMIN меняет СТРУКТУРУ аргументов графа, а граф берётся старый. В лучшем
# случае это assert, в худшем -- чтение по чужому адресу, то есть тихая порча (CLAUDE.md §4).
# Диагноз доказан положительным контролем: с отдельным VLLM_CACHE_ROOT та же конфигурация
# поднимается, с общим -- падает. Стенд и боевой делят этот каталог, поэтому опыт на стенде
# ОТРАВЛЯЛ боевой: он падал бы при следующем подъёме, ничего своего не меняя.
# Лечение: в путь кэша входит отпечаток рычагов, меняющих структуру графа.
# [09.09] ВТОРОЕ ТЕЛО ОДНОЙ ЛОГИКИ -- И ОНО ЧУТЬ НЕ СТОИЛО БОЕВОГО. Такой же `_STRUKT` есть
# в serve_qwen38_int8.sh; MTP_W8 был добавлен ТУДА, а здесь отпечаток считается РАНЬШЕ и
# экспортирует VLLM_CACHE_ROOT, после чего `:-` в базовом пускаче уже пустышка. В журнале это
# видно двумя разными числами в одной строке: «кэш ... _80c7a740 (otpechatok 89380608)».
# Каталог 80c7a740 лежал с 31 августа -- новый граф черновика получил бы СТАРЫЕ тела, то есть
# ровно тот отказ, ради которого отпечаток и заведён. Держим оба списка одинаковыми.
