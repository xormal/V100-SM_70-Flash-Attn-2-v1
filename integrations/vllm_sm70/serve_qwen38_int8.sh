#!/usr/bin/env bash
# ===============================================================================================
# ПУСКАЧ Qwen3.8-27B в int8 (основная масса) + i12 (внимание), KV-пул в int8.
#
# ПРОИЗВОДНЫЙ ОТ serve_qwen36_int8.sh НАМЕРЕННО: там накоплено знание об окружении (каталог
# сборки по порту, наследование tmux, порядок EXTRA_ARGS, режимы диалога и длинного промпта),
# и переписывать его заново значило бы потерять всё это молча.
#
# ЧЕМ ЭТА СЕТЬ ОТЛИЧАЕТСЯ ОТ 3.6: НИЧЕМ ПО СТРОЕНИЮ. Сверка config дала совпадение по ВСЕМ 33
# параметрам (hidden 5120, intermediate 17408, head_dim 256, 64 слоя = 48 GDN + 16 полного
# внимания, словарь 248320). Поэтому ядра НЕ менялись -- и это проверено сверкой, а не надеждой.
# Отличается ОБВЯЗКА: свой шаблон (думающий, с reasoning_effort), свои eos, XML-вызовы
# инструментов -> --tool-call-parser qwen3_coder и --reasoning-parser qwen3 (как в рецепте).
#
# ЯВНОЕ enable_thinking=true -- НЕ ИЗБЫТОЧНОСТЬ, А ПОЧИНКА. Умолчания шаблона и разборчика
# РАСХОДЯТСЯ: шаблон при неуказанном enable_thinking считает его ИСТИННЫМ и открывает <think> уже
# в промпте, а Qwen3ReasoningParser берёт его как chat_kwargs.get("enable_thinking", False), то есть
# ЛОЖНЫМ, ищет открывающий тег в выводе, не находит и МОЛЧА выбрасывает всё рассуждение. Ответ при
# этом верный и ничего не падает -- ломается только поле reasoning_content, то есть контракт API.
# Проверено сырым выводом в обход разборщика: модель думает и считает верно (17*23=391).
#
# ЗАМЕРЕНО НА ЭТОЙ СЕТИ (пара 0-1, промпт ~24 тыс. слов, медиана из 3):
#     dialog     (TP=2, обмен int12)   62.14 с
#     longprompt (PP=2, кусок 4096)    28.62 с   = x2.17
# Причина в ОПИСИ ПУТИ ПО ЯДРАМ (tools/opis_puti.py, лента профилировщика движка): при тензорном
# разрезе 62.0 % времени карты держит ОДИН ncclDevKernel_AllGather -- 521 пуск по 12.7 мс. Наши
# тела там 4.6 %, карта занята 98.8 %, простой 1.2 %. То есть на длинном промпте связывает ПРОВОД,
# и снимает это не ядро, а СМЕНА ЕДИНИЦЫ РАЗРЕЗА: у конвейера одна передача на стык вместо 128
# свёрток на кусок.
#
# ОТКУДА ВЗЯЛСЯ СЛЕПОК: tools/quantize_gptq_rtn.py, BF16 55.6 ГБ -> int8 в формате GPTQ.
# Условность нулевой точки проверена ЗАМЕРОМ против ядра движка (tools/gptq_uslovnost.py).
# ===============================================================================================
# Подъём Qwen3.6-27B-INT8 с ядрами sm_70. ОДИН скрипт для боевого и тестового запуска.
#
#   PORT=8091 CARDS=0,1 ./serve_qwen38_int8.sh     # эта сеть (умолчание)
#   Боевая Qwen3.6 живёт на 8085/картах 2-3 своим пускачом -- НЕ ПЕРЕСЕКАТЬСЯ.
#
# ЗАЧЕМ ОН НУЖЕН (написан 03.08.2026 по итогам 40-минутного простоя боевого сервера).
# Перезапуск руками провалился ТРИЖДЫ, и каждый раз причина была одна и та же по классу:
# НЕПОЛНОЕ ИЛИ ЧУЖОЕ ОКРУЖЕНИЕ, а признак — МОЛЧАЛИВОЕ ЗАВИСАНИЕ, без ошибки и без трассы.
#   1) CUDA_HOME не задан -> воркер падает при сборке расширения;
#   2) КОМПИЛЯТОР ХОСТА НАСЛЕДУЕТСЯ из оболочки (base-conda даёт
#      x86_64-conda-linux-gnu-cc, он новее gcc 14) -> nvcc из CUDA 12.8 отвергает его
#      наглухо: crt/host_config.h:143 "gcc versions later than 14 are not supported";
#   3) сборка идёт ЛЕНИВО в двух воркерах сразу -> они дерутся за файл замка,
#      один держит его многие минуты, движок ждёт «No available shared memory broadcast
#      block» по кругу, и в журнале НЕТ НИ ОДНОЙ строки со словом ERROR.
# Поэтому здесь: (а) окружение сборки ЗАДАЁТСЯ, а не наследуется, и годность компилятора
# доказывается ПРОБНОЙ СБОРКОЙ через сам nvcc; (б) расширения собираются ЗАРАНЕЕ, В ОДНОМ
# процессе, с ПОТОКОВЫМ выводом, и отказ сборки ВИДЕН; (в) осиротевшие замки снимаются, но
# только те, которых НЕ ДЕРЖИТ живой процесс; (г) каталог сборки разведён по порту, чтобы
# тестовый прогон не мог перезаписать библиотеки боевого.

set -euo pipefail

die() { echo "ОТКАЗ: $*" >&2; exit 1; }
say() { echo "[$(date +%H:%M:%S)] $*"; }

# СНИМОК ОКРУЖЕНИЯ ДО ЛЮБОЙ НАШЕЙ ПРАВКИ. Нужен, чтобы в конце назвать переменные, которые
# ПРИШЛИ ИЗВНЕ и скрипт их НЕ перекрывает: именно такая протечка (NCCL_P2P_DISABLE=0 от
# запуска на других картах) повесила подъём молча. Невидимое наследование — главный класс
# отказов этого скрипта; здесь оно становится строкой в журнале.
_env_before="$(printenv | grep -E '^(VLLM_|NCCL_|TORCH_|CUDA_|PYTORCH_|FA2SM70_|HF_|TRANSFORMERS_|CC=|CXX=)' | sort || true)"

PORT="${PORT:-8091}"
CARDS="${CARDS:-0,1}"
MODEL="${MODEL:-/mnt/d1/alex/VLLM_ch/Qwen3.8-27B_int8_i12}"
RUNDIR=/mnt/d1/alex/VLLM_ch/run
PROD_PORT=8085                    # каталог сборки принадлежит ЭТОМУ серверу и никому больше

# КАТАЛОГ СБОРКИ РАЗВЕДЁН ПО ПОРТУ НАМЕРЕННО, И ЭТО НЕ ПЕДАНТИЗМ.
# Боевой сервер читает .fa2sm70_build. Если тестовый прогон соберётся в тот же каталог с
# другими флагами (например, другим компилятором хоста), он ПЕРЕЗАПИШЕТ библиотеки, которые
# боевой возьмёт при следующем подъёме. Это не упадёт и не сигналит — оно тихо подменит
# машинный код чужой сборкой. Владение каталогом обязано совпадать с владением сервером.
if [ -n "${FA2SM70_BUILD_DIR:-}" ]; then
  BUILD_DIR="$FA2SM70_BUILD_DIR"
elif [ "$PORT" = "$PROD_PORT" ]; then
  BUILD_DIR="$RUNDIR/.fa2sm70_build"
else
  BUILD_DIR="$RUNDIR/.fa2sm70_build_p$PORT"
fi
# ДВЕ ВЕТКИ ДЕРЕВА ЯДЕР: боевая собирается из ЗАКРЕПЛЁННОГО СЛЕПКА, тестовая -- из рабочего.
#
# ЗАЧЕМ. Здесь стояло одно значение на оба случая -- рабочее дерево, -- и это значило, что ЛЮБАЯ
# незавершённая правка попадает в боевой при следующем подъёме. Цена вскрылась 07.08.2026: сбой
# электричества, подъём боевого, и вместо секунд -- ПЯТНАДЦАТЬ МИНУТ пересборки cutlass, потому
# что в дереве лежали правки того же дня. Сломанная правка тем же путём уронила бы боевой, причём
# не в момент правки, а при ближайшем перезапуске -- то есть в самый неудобный момент.
#
# ПРАВИЛО. Боевой берёт слепок. Слепок обновляется НАМЕРЕННЫМ действием -- run/promote_to_prod.sh,
# который снимает копию, ставит отметку и требует, чтобы проверка поведением была пройдена.
# Тестовые порты берут рабочее дерево: там правки и обкатываются.
# Переопределение FA2SM70_PATH работает как раньше и старше обоих правил.
PROD_TREE=/mnt/d1/alex/VLLM_fa2_prod/fa2_sm70_cutlass_grade
WORK_TREE=/mnt/d1/alex/VLLM_fa2/solutions/fa2_sm70_cutlass_grade
if [ -n "${FA2SM70_PATH:-}" ]; then
  FA2="$FA2SM70_PATH"
elif [ "$PORT" = "$PROD_PORT" ] && [ -d "$PROD_TREE" ]; then
  FA2="$PROD_TREE"
else
  FA2="$WORK_TREE"
fi
PY="${PY:-/mnt/d1/alex/VLLM_ch/.venv-1cat-vllm/bin/python}"
_STAMP="$(date +%Y%m%d_%H%M%S)"
LOG="$RUNDIR/serve_${PORT}_${_STAMP}.log"
# В сухом прогоне журнал СВОЙ: иначе tee создаст файл с именем боевого журнала и в описи
# запусков появится пустышка, неотличимая от упавшего подъёма.
[ "${FA2SM70_DRYRUN:-0}" = "1" ] && LOG="$RUNDIR/.dryrun_${PORT}.log"
WARM_LOG="$RUNDIR/warm_${PORT}_${_STAMP}.log"


# ---------------------------------------------------------------- окружение
_inherited_cc="${CC:-}"          # запоминаем, чтобы честно сказать, что отбросили
# CUDA_HOME наследуется НАМЕРЕННО (разные машины — разные наборы), но годность его
# доказывается не наличием каталога, а тем, что ЕГО nvcc собирает пробное тело под sm_70
# (блок «компилятор хоста» ниже). Наличие каталога ничего не значит.
export CUDA_HOME="${CUDA_HOME:-/home/alex/miniconda3/envs/cuda128}"
# [ВЫБОР УСТРОЙСТВ CUDA ПО UUID -- 11.09, авария карты 0]
# После исчезновения карты CUDA перечисляет только ЖИВЫЕ устройства, и индексы перестают
# значить то, что значили: `CUDA_VISIBLE_DEVICES=2,3` дал ОДНУ карту вместо двух (проверено
# 11.09, когда карта 0 отвалилась от шины). UUID к этому невосприимчив. Индексы при этом
# остаются верными для nvidia-smi -- у него нумерация не сдвигается, поэтому проверки
# занятости и топологии по-прежнему идут по $CARDS.
export CUDA_VISIBLE_DEVICES="${FA2SM70_CVD:-$CARDS}"
export CUDA_DEVICE_ORDER=PCI_BUS_ID
# ФРАГМЕНТАЦИЯ ПУЛА -- ОТКАЗ ПО ПАМЯТИ НА ДЛИННОМ ПРОМПТЕ (дефект #169). Замерено 11.08.2026:
# без этого игла на 64000 слов роняет движок с OOM при 2.49 ГиБ "reserved but unallocated";
# с ним -- 6/6 игл, ноль OOM, сервер жив. ИМЯ ВАЖНО: torch 2.9 читает ТОЛЬКО
# PYTORCH_CUDA_ALLOC_CONF (проверено `strings libc10_cuda.so`), новое имя PYTORCH_ALLOC_CONF в
# этой сборке НЕ читается вовсе -- то есть выглядит выставленным и не действует.
export PYTORCH_CUDA_ALLOC_CONF="${PYTORCH_CUDA_ALLOC_CONF:-expandable_segments:True}"
# Новое имя ставится ЗА КОМПАНИЮ, на будущие сборки. В ЭТОЙ оно не действует: строкой выше
# записано, что torch 2.9 читает только PYTORCH_CUDA_ALLOC_CONF (проверено `strings`), и мой
# утренний вывод "новое имя надо выставить, иначе не действует" был ошибкой -- предупреждение
# о deprecated печатает не тот слой, что читает переменную.
export PYTORCH_ALLOC_CONF="${PYTORCH_ALLOC_CONF:-$PYTORCH_CUDA_ALLOC_CONF}"
export TORCH_CUDA_ARCH_LIST=7.0
export HF_HUB_OFFLINE=1
export TRANSFORMERS_OFFLINE=1
export NCCL_CUMEM_ENABLE=0

# ПРЯМАЯ ПЕРЕДАЧА МЕЖДУ КАРТАМИ — определяется ПО ТОПОЛОГИИ, а не ставится наугад.
# На нашей машине NVLink есть ТОЛЬКО между 2 и 3; карты 0-1 связаны мостом PCIe (PHB).
# С включённой прямой передачей подъём на паре БЕЗ NVLink ВИСНЕТ НАМЕРТВО (замерено при
# подъёме четырёх сеток 03.08: обе карты 100 %, ~477 МиБ, девять минут без движения).
# РЕШАЕТ ТОПОЛОГИЯ, И ТОЛЬКО ОНА. Унаследованное значение здесь НЕ уважается — и это
# доказано отказом: 03.08 в оболочке остался NCCL_P2P_DISABLE=0 от боевого перезапуска
# (карты 2-3, где NVLink ЕСТЬ), прежняя проверка «задано снаружи — не трогаем» его уважила,
# и подъём на 0-1 встал НАМЕРТВО на pynccl.py:111: обе карты, 469 МиБ, восемь минут без
# единой строки. То есть определение топологии было выключено ровно тем, от чего защищает.
#
# ПЕРЕСМОТРЕНО 21.08.2026 ЗАМЕРОМ -- ЗАПРЕТ ВЫШЕ ПРОТУХ, И ОН СТОИЛ ТРЕТИ ПРЕФИЛЛА.
# Отказ 03.08 был реальным, но привязка «нет NVLink -> нет прямой передачи» НЕВЕРНА: P2P через
# PCIe -- отдельная от NVLink вещь, и `nvidia-smi topo -p2p r` даёт OK для ВСЕХ пар, включая 0-1.
# Проверено поведением 21.08: подъём с NCCL_P2P_DISABLE=0 на паре 0-1 проходит (147 с), гейт
# 391 чистый, повтор/ветвление/игла на 35K пройдены. Замер префилла (128K, тот же прибор):
#     P2P выключен: 156.9 с, обмен внутри 80.5 с, полоса 1.6 ГБ/с (шло ЧЕРЕЗ ХОСТ)
#     P2P включён:  103.2 с, обмен внутри 26.7 с, полоса 4.8 ГБ/с   -> x1.52
# По всей кривой x1.70 / x1.66 / x1.52 на 35K / 64K / 128K. Поэтому решает ТЕПЕРЬ НЕ NVLink,
# а поддержка P2P: спрашиваем её у драйвера, а не выводим из типа моста.
# ОТКАТ, если отказ 03.08 воспроизведётся на другой машине: FA2SM70_P2P=1.
_c1="${CARDS%%,*}"; _c2="${CARDS##*,}"
if nvidia-smi topo -m 2>/dev/null | awk -v a="GPU$_c1" -v b="$((_c2+2))" '$1==a{print $b}' | grep -q "^NV"; then
  _p2p=0; _why="есть NVLink"
elif nvidia-smi topo -p2p r 2>/dev/null | awk -v a="GPU$_c1" -v b="$((_c2+2))" '$1==a{print $b}' | grep -q "OK"; then
  _p2p=0; _why="NVLink нет, но драйвер даёт P2P через PCIe (замерено 21.08: префилл x1.52)"
else
  _p2p=1; _why="прямая передача НЕ поддержана драйвером"
fi
# Переопределить можно только ОТДЕЛЬНЫМ именем, чтобы случайно унаследованная
# NCCL_P2P_DISABLE не могла отменить решение по топологии молча.
if [ -n "${FA2SM70_P2P:-}" ] && [ "$FA2SM70_P2P" != "$_p2p" ]; then
  say "ВНИМАНИЕ: FA2SM70_P2P=$FA2SM70_P2P перекрывает решение по топологии ($_p2p, $_why)"
  _p2p="$FA2SM70_P2P"
fi
if [ -n "${NCCL_P2P_DISABLE:-}" ] && [ "$NCCL_P2P_DISABLE" != "$_p2p" ]; then
  say "унаследованная NCCL_P2P_DISABLE=$NCCL_P2P_DISABLE ОТБРОШЕНА (топология карт $CARDS требует $_p2p)"
fi
export NCCL_P2P_DISABLE="$_p2p"
say "топология карт $CARDS: $_why -> NCCL_P2P_DISABLE=$_p2p"
export VLLM_ROOT=/mnt/d1/alex/VLLM_ch
export VLLM_USE_V1=1
# ВЫБОР БЭКЕНДА ВНИМАНИЯ. Умолчание -- боевой FLASH_ATTN_V100. Переопределяется ОТДЕЛЬНЫМ
# именем FA2SM70_BACKEND, а не наследованием VLLM_ATTENTION_BACKEND: случайная переменная в
# оболочке не должна молча подменять боевой путь (тот же класс, что уронил подъём 03.08).
# FA2_SM70 -- наш второй бэкенд, перенесённый в это дерево 04.08; вне списка приоритета sm_70,
# то есть без этой переменной он НЕ выбирается никогда.
# УМОЛЧАНИЕ СМЕНЕНО 19.08.2026: НАТИВНЫЙ КОНТУР. Прежним умолчанием была прокладка
# (FLASH_ATTN_V100) -- разумно, пока наш бэкенд был опытным. Теперь он проверен приёмкой
# (research/23, задачи 162/193) и БЫСТРЕЕ прокладки, а держать разные умолчания у стенда и у
# боевого -- это ровно то расхождение двух тел, на котором мы уже горели: боевой ходил
# нативно, а стенд молча мерил ПРОКЛАДКУ, и сравнивать их было нельзя. Откат одной
# переменной: FA2SM70_BACKEND=FLASH_ATTN_V100.
export VLLM_ATTENTION_BACKEND="${FA2SM70_BACKEND:-FA2_SM70}"
# ОДНОЙ ПЕРЕМЕННОЙ МАЛО, И ЭТО ЗАМЕРЕНО: при VLLM_ATTENTION_BACKEND=FA2_SM70 движок молча
# взял FLASH_ATTN_V100 («out of potential backends: ['FLASH_ATTN_V100','TRITON_ATTN']»),
# потому что выбор ограничен списком приоритета платформы. Поэтому нужен ВТОРОЙ ключ,
# который вводит бэкенд в сам список (platforms/cuda.py). Без него подъём НЕ падает, а тихо
# идёт прежним путём — то есть A/B сравнил бы один бэкенд сам с собой.
if [ "$VLLM_ATTENTION_BACKEND" = "FA2_SM70" ]; then
  export VLLM_SM70_FA2=1
fi
say "бэкенд внимания: $VLLM_ATTENTION_BACKEND$([ -n "${FA2SM70_BACKEND:-}" ] && echo " (явно; VLLM_SM70_FA2=${VLLM_SM70_FA2:-0})")"
export VLLM_FLASH_V100_ENABLE_PAGED_PREFILL=1
export VLLM_SM70_ENABLE_LM_HEAD_FASTPATH=1
export VLLM_ALLOW_LONG_MAX_MODEL_LEN=1
export VLLM_GPTQ_ZERO_C=fold
export FA2SM70_PATH="$FA2"
export FA2SM70_BUILD_DIR="$BUILD_DIR"
export FA2SM70_SHIM_PREFILL=1 FA2SM70_SHIM_DECODE=1 FA2SM70_SHIM_STORE=1
export FA2SM70_KV_I8=1 FA2SM70_KV_I8_BYTES=1
# Остальные три рычага нативного контура -- тем же решением и с теми же основаниями:
#   PAGED_PREFILL -- префилл читает страницы int8-пула НАПРЯМУЮ (без gather и плит сборки);
#   TM8           -- turbomind-двигатель на нашем GPTQ-8 в зоне средних M (лестница 19.08);
#   GDN_REC       -- наш рекуррент декода вместо чужого Triton (ветка в самом vllm-коде).
export FA2SM70_PAGED_PREFILL="${FA2SM70_PAGED_PREFILL:-1}"
# tm8 (turbomind-двигатель для зоны 16<M<=512) ВЫКЛЮЧЕН ПО УМОЛЧАНИЮ -- решение владельца
# 20.08 по замеру: pack держит 3034 МиБ на карту (половину KV боевого), а при крупном чанке
# его зона почти не встречается (1 срабатывание за прогон). Размен замерен: выключение даёт
# ёмкость 86 016 -> 129 024 токенов (+50 %) при неизменных префилле и декоде.
# Включение осознанное: FA2SM70_TM8=1 (и тогда урезать KV на объём pack).
# [ПОРЯДОК ВАЖЕН -- МИНА, ПОЙМАННАЯ ТРАССОЙ 25.08] Этот блок обязан стоять ДО строки
