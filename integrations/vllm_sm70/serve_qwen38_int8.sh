# ПРОВЕРЕНО 21.08 И ЗАКРЫТО: НЕ РАБОТАЕТ ВМЕСТЕ С ГРАФОМ. Подъём падает на
# `custom_all_reduce.cuh:455 'invalid argument'` -- это `cudaIpcGetMemHandle` на буферах
