# ------------------------------------------------- КОМПИЛЯТОР ХОСТА ДЛЯ nvcc
# УНАСЛЕДОВАННОЕ ЗНАЧЕНИЕ ЗДЕСЬ — ЛОВУШКА, И ОНА СРАБОТАЛА (03.08, обкатка на 0-1).
# Оболочка (base-conda) задаёт CC=x86_64-conda-linux-gnu-cc; он новее gcc 14, и nvcc из
# CUDA 12.8 отвергает его наглухо: crt/host_config.h:143 "gcc versions later than 14 are
# not supported". Прежняя запись `CC="${CC:-/usr/bin/gcc}"` унаследованное ЗНАЧЕНИЕ
# СОХРАНЯЛА, поэтому умолчание не применялось никогда, а боевой запуск уцелел лишь
# потому, что там CC передавался явным `env`.
#
# Поэтому здесь компилятор НЕ наследуется, а ВЫБИРАЕТСЯ, и годность его доказывается
# ПОВЕДЕНИЕМ — пробной сборкой через тот самый nvcc, а не именем, версией или наличием
# файла (проверка по имени и есть то, что нас уронило).
# Явно переопределить можно переменной FA2SM70_CC (тогда проверка та же).
_probe_dir="$(mktemp -d)"; trap 'rm -rf "$_probe_dir"' EXIT
printf '#include <cuda_runtime.h>\n__global__ void k(){}\nint main(){return 0;}\n' > "$_probe_dir/p.cu"
_cc_ok=""
for _cand in ${FA2SM70_CC:-} /usr/bin/gcc /usr/bin/gcc-14 /usr/bin/gcc-13 /usr/bin/gcc-12 /usr/bin/gcc-11; do
  [ -x "$_cand" ] || continue
  _cxx="$(echo "$_cand" | sed 's/gcc/g++/')"
  [ -x "$_cxx" ] || continue
  if "$CUDA_HOME/bin/nvcc" -ccbin "$_cand" -gencode=arch=compute_70,code=sm_70 \
       -std=c++17 -c "$_probe_dir/p.cu" -o "$_probe_dir/p.o" >"$_probe_dir/err" 2>&1; then
    _cc_ok="$_cand"; break
  fi
  say "  компилятор $_cand ОТВЕРГНУТ nvcc: $(grep -m1 -o 'error[^\"]*' "$_probe_dir/err" | cut -c1-90)"
done
[ -n "$_cc_ok" ] || die "ни один компилятор хоста не принят nvcc из $CUDA_HOME. Последняя ошибка: $(tail -3 "$_probe_dir/err")"
export CC="$_cc_ok"
export CXX="$(echo "$_cc_ok" | sed 's/gcc/g++/')"
export CUDAHOSTCXX="$CXX"
if [ -n "${_inherited_cc:-}" ] && [ "$_inherited_cc" != "$CC" ]; then
  say "компилятор: унаследованный $_inherited_cc ОТБРОШЕН, взят $CC ($("$CC" -dumpversion))"
else
  say "компилятор: $CC ($("$CC" -dumpversion)) — пробная сборка через nvcc прошла"
fi

