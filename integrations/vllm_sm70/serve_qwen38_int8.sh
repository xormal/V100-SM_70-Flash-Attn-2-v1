# ------------------------------------------- что пришло извне и НЕ перекрыто скриптом
# Список управляемых имён берётся ИЗ САМОГО СКРИПТА, а не пишется руками: рукописный список
# разошёлся бы с кодом молча, и опись начала бы врать в ту же сторону, что и всё остальное
# здесь — «выглядит проверенным, не проверено».
# Берём ВСЕ имена строки, а не первое: у нас есть строки вида `export A=1 B=1 C=1`, и разбор
# «по первому имени» тихо объявил бы B и C протечками.
# СПИСОК УПРАВЛЯЕМЫХ ИМЁН -- ПО ОБОИМ ТЕЛАМ, А НЕ ТОЛЬКО ПО ЭТОМУ. Боевая обёртка выставляет
# часть переменных сама (нативный контур, имена, каталоги), и без её разбора детектор числил
# бы их «унаследованными извне»: пятнадцать строк шума, в которых НАСТОЯЩАЯ протечка не видна.
# Прибор, который всегда горит, — не прибор.
