# [MTP -- СПЕКУЛЯТИВНЫЙ ДЕКОД ЧЕРНОВИКОМ ИЗ СЛЕПКА] FA2SM70_MTP=<k> (0 = выкл, умолчание).
# Замер 19.08 (стенд, TP=2, int8 KV): k=3 даёт 41.5 ток/с против 33.2 без спекуляции и 21.7 на
# PP-конвейере; на боевых картах через NVLink -- 46.5 против 34.1 (x1.36). Жадный выход
# тождествен по построению (rejection sampling).
#
# ПОЧЕМУ НЕ УМОЛЧАНИЕ: СПЕКУЛЯЦИЯ И ПРЕФИКС-КЭШ ЗДЕСЬ НЕСОВМЕСТИМЫ, И ЭТО ПРОВЕРЕНО, А НЕ
# УНАСЛЕДОВАНО. Цепочка целиком (19.08):
#   1. Сеть гибридная: 48 слоёв GDN несут РЕКУРРЕНТНОЕ состояние, а не KV-страницы. Префикс-кэш
#      умеет возвращать страницы, но не состояние, поэтому движок переводит mamba-кэш в режим
#      'align' -- он ставит границы блоков так, чтобы состояние можно было взять на границе.
#   2. УСТАРЕЛО 21.08 (задача 194 ЗАКРЫТА): режим 'all' РЕАЛИЗОВАН на нашем пути и запрет в
#      модели снят. Состояние GDN сохраняется по границам блоков (префилл режет кусок на
#      отрезки, декод пишет через ssm_state_indices_out), поэтому кэш и спекуляция работают
#      ВМЕСТЕ. Гейт: повтор 35K промпта даёт ТОТ ЖЕ ответ при x5.2 ускорении, ветвление с
#      середины верно, игла на глубине найдена. Ёмкость НЕ падает: 1.44x на 262K, как и в
#      'align' (прежняя оценка «~98K» была снята с ЛЖИВОЙ строки GPU KV cache size).
#   3. Значит остаётся 'align' + спекуляция, а на это в движке стоит assert. Мы сняли его
#      рычагом (FA2SM70_ALIGN_SPEC=1) и ПРОВЕРИЛИ ГЕЙТОМ ТОЖДЕСТВЕННОСТИ: на 15K префиксе при
#      попадании в кэш (x2.56 по времени) ответ РАЗОШЁЛСЯ с некэшированным (хэши 43c2b1f8a809
#      против 4cb89d5bbc7b). Короткие случаи и ветвление прошли -- порча ТИХАЯ, видна только
#      на длинном префиксе. Запрет авторов обоснован.
# ИТОГ: с MTP префикс-кэш ГАСИТСЯ. Для диалогового боевого это проигрыш (ход на 15K префиксе
# 3.01 с с кэшем против 8.35 без), поэтому боевой ходит БЕЗ спекуляции; MTP -- для генеративных
# нагрузок с длинным выводом и коротким промптом. Настоящая починка -- реализовать
# mamba_cache_mode='all' для Qwen3.5 (задача 87); тогда оба рычага сложатся.
if [ "${FA2SM70_MTP:-0}" != "0" ]; then
  # БЕЗ --mamba-cache-mode align: движок ОТВЕРГАЕТ его вместе со спекуляцией
  # («Mamba cache mode 'align' is currently not compatible with speculative decoding»).
  # Режим кэша mamba оставляем движку; рычаг для опыта -- FA2SM70_MAMBA_MODE.
  _SPLIT="$_SPLIT --speculative-config {\"method\":\"qwen3_5_mtp\",\"num_speculative_tokens\":${FA2SM70_MTP}}"
  # ДВА РЫЧАГА НА ОДНО РЕШЕНИЕ -- ЭТО МИНА: FA2SM70_MAMBA_ALL=1 без MAMBA_MODE=all оставлял
  # кэш ВКЛЮЧЁННЫМ в режиме 'align', то есть ровно ту тихую порчу, от которой ветка и защищает.
  # Поэтому ALL сам ставит режим, а явный MAMBA_MODE остаётся рычагом для опыта.
  if [ "${FA2SM70_MAMBA_ALL:-0}" = "1" ] && [ -z "${FA2SM70_MAMBA_MODE:-}" ]; then
    FA2SM70_MAMBA_MODE=all
  fi
  if [ "${FA2SM70_MAMBA_ALL:-0}" = "1" ] && [ "${FA2SM70_MAMBA_MODE}" != "all" ]; then
    die "FA2SM70_MAMBA_ALL=1 требует режима 'all', а задан '${FA2SM70_MAMBA_MODE}': в 'align' кэш со спекуляцией портит выход ТИХО"
  fi
  [ -n "${FA2SM70_MAMBA_MODE:-}" ] && _SPLIT="$_SPLIT --mamba-cache-mode ${FA2SM70_MAMBA_MODE}"
  # РЕЖИМ 'all' СНИМАЕТ САМ ЗАПРЕТ (задача 194): состояние GDN сохраняется по границам
  # блоков, поэтому спекуляция и префикс-кэш работают ВМЕСТЕ, а не по очереди. Цена -- не
  # точность, а ЁМКОСТЬ: страницы держат все 64 слоя, и контекст при том же пуле ~98K вместо
  # ~392K. Поэтому кэш при MTP гасится только там, где 'all' НЕ включён.
  if [ "${FA2SM70_MAMBA_ALL:-0}" = "1" ]; then
    say "СПЕКУЛЯЦИЯ MTP: k=${FA2SM70_MTP} + префикс-кэш ВМЕСТЕ (режим mamba-кэша 'all')"
  elif [ "${FA2SM70_MTP_PREFIX:-0}" = "1" ]; then
    # Только для опыта и ТОЛЬКО вместе с FA2SM70_ALIGN_SPEC=1: см. пункт 3 выше -- выход
    # перестаёт быть воспроизводимым при попадании в кэш.
    say "СПЕКУЛЯЦИЯ MTP: k=${FA2SM70_MTP}; префикс-кэш ОСТАВЛЕН ЯВНЫМ РЫЧАГОМ (выход не гарантирован)"
  else
    _PREFIX_FLAG="--no-enable-prefix-caching"
    say "СПЕКУЛЯЦИЯ MTP: k=${FA2SM70_MTP} (черновик bf16 из слепка); префикс-кэш выключен -- порча проверена гейтом"
  fi
fi
# [FA2/SM70] РАЗЛОЖЕНИЕ ПО СРЕЗУ И ПЕРЕКРЫТИЕ ОБМЕНА (задача 201).
# FA2SM70_SEQPAR=1  -- sequence parallelism: активации режутся по ТОКЕНАМ между картами,
#   all_reduce превращается в reduce_scatter + норма на срезе + all_gather. Идёт через обычные
#   коллективы vLLM, symmetric memory НЕ требует -- работает и на PCIe.
# FA2SM70_ASYNCTP=1 -- поверх него слияние GEMM с обменом (torch.ops.symm_mem.*): обмен куска
#   перекрывается вычислением следующего. ТРЕБУЕТ P2P между картами, то есть NVLink; на стенде
#   (карты 0-1, мост PCIe, NCCL_P2P_DISABLE=1) НЕ поднимется -- это ожидаемо, не дефект.
_PASSCFG=""
# [29.08] СЛИЯНИЕ all-reduce С НОРМОЙ. Опись шага декода: 129 коллективов за шаг по 55 мкс =
# 7.10 мс, полезной нагрузки 10 КиБ -- то есть ЧИСТАЯ ЛАТЕНТНОСТЬ, а не полоса. У vLLM есть
# проход `fuse_allreduce_rms`, который сшивает коллектив со следующей нормой; у нас он был
# выключен и НИ РАЗУ не проверялся. Умолчание не меняем: FA2SM70_FUSE_AR_RMS=1.
if [ "${FA2SM70_FUSE_AR_RMS:-0}" = "1" ]; then
  _PASSCFG=",\"pass_config\":{\"fuse_allreduce_rms\":true}"
  say "СЛИЯНИЕ all-reduce с нормой ВКЛЮЧЕНО (проверка рычага)"
fi
if [ "${FA2SM70_SEQPAR:-0}" = "1" ] || [ "${FA2SM70_ASYNCTP:-0}" = "1" ]; then
  _sp=true; _fc=false
  [ "${FA2SM70_ASYNCTP:-0}" = "1" ] && _fc=true
  _PASSCFG=",\"pass_config\":{\"enable_sp\":${_sp},\"fuse_gemm_comms\":${_fc}}"
  say "РАЗРЕЗ ПО СРЕЗУ: sequence_parallelism=${_sp}, перекрытие обмена (async TP)=${_fc}"
  if [ "$_fc" = "true" ] && [ "${NCCL_P2P_DISABLE:-0}" = "1" ]; then
    say "ВНИМАНИЕ: async TP просит P2P, а он выключен по топологии -- ожидается отказ или откат паса"
  fi
fi
cd "$RUNDIR/.rundir_fa2sm70"
# [29.08] СПИСОК РАЗРЕЗАЮЩИХ ОПЕРАЦИЙ -- ПЕРЕМЕННОЙ.
# Профиль шага декода (25 шагов, только декод) назвал главную статью: `gdn_attention_core`
# тратит 20.97 мс ПИТОНА на шаг (437 мкс на слой x 48 слоёв) при 0.81 мс работы карты.
