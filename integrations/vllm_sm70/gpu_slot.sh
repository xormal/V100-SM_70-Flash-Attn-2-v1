#!/usr/bin/env bash
# ЗАМОК НА СЛОТ КАРТ (по умолчанию 0-1, карты для разработки).
#
# ЗАЧЕМ ОН СУЩЕСТВУЕТ. Эта модель при TP=2 занимает ~18.1 ГиБ на карту минимум (веса 15.52 +
# контекст CUDA 0.6 + активации ~1.5 + графы 0.5), поэтому на паре 32-ГиБ карт помещается РОВНО
# ОДИН экземпляр -- ни при каком --gpu-memory-utilization их не станет два. А подъёмник по
# умолчанию просит util=0.90, то есть каждый запуск забирает почти всю карту независимо от нужды.
#
# ПОЧЕМУ ВЕЖЛИВОСТИ НЕДОСТАТОЧНО, И ЭТО ГЛАВНОЕ. Между проверкой "свободно ли" и стартовым
# контролем памяти внутри vLLM проходит ~40 секунд загрузки весов. Кто первый дошёл до контроля,
# тот и взял слот; остальные падают с "Free memory on device cuda:N is less than desired GPU
# memory utilization". Значит слот достаётся не тому, кому нужнее, а тому, кто чаще опрашивает.
# Наблюдалось живьём: три подъёма одного замера сорваны подряд, а один раз ТРИ сервера
# одновременно грузили веса в одну карту и отбирали память друг у друга.
#
# ВТОРАЯ ПРИЧИНА -- ИМЕННО ЭТА ОШИБКА СТОИЛА ЧУЖОГО ЗАМЕРА. Порт НЕ идентифицирует владельца,
# если владельцев двое: два независимых механизма захвата, каждый "убирающий только свой порт",
# гарантированно съедают друг друга. Владельца различает только PID, записанный в момент запуска.
# Отсюда устройство замка: держатель -- это PID, и liveness проверяется через kill -0.
#
# УСТРОЙСТВО. mkdir атомарен на POSIX -- это и есть весь механизм, никаких флоков и сравнений
# таймстампов, которые сами имеют гонку. Замок САМОЧИСТЯЩИЙСЯ: подъёмник пишет pid=$$ и затем
# делает exec, поэтому держателем оказывается сам сервер, и когда он умирает (любым способом,
# включая kill -9 и падение) следующий желающий видит мёртвый PID и снимает замок. Забытых
# замков не бывает по построению, trap не нужен.
#
# ИСПОЛЬЗОВАНИЕ:
#   gpu_slot.sh acquire <имя> <зачем> [минут] [pid]   # ждёт очереди, печатает OK когда слот твой
#   gpu_slot.sh release <имя>                         # отдать (только свой)
#   gpu_slot.sh status                                # кто держит, сколько, что свободно
# Отключается переменной GPU_SLOT_LOCK=0 (например, для карт 2-3, где стоит боевой сервер).
set -u
LOCK_DIR="${GPU_SLOT_DIR:-/tmp/fa2sm70_gpu_slot}"
L="$LOCK_DIR/${GPU_SLOT_NAME:-gpu01}.lock"
mkdir -p "$LOCK_DIR" 2>/dev/null || true

_info() { sed -n "s/^$1=//p" "$L/info" 2>/dev/null; }

case "${1:-status}" in
acquire)
  NAME="${2:?нужно имя}"; WHY="${3:-}"; MIN="${4:-45}"; MYPID="${5:-$$}"
  for i in $(seq 1 720); do                      # до 2 часов
    if mkdir "$L" 2>/dev/null; then
      { echo "owner=$NAME"; echo "pid=$MYPID"; echo "why=$WHY"
        echo "since=$(date +%s)"; echo "ttl_min=$MIN"; } > "$L/info"
      echo "[слот] ВЗЯТ: $NAME ($WHY), pid=$MYPID, лимит ${MIN} мин" >&2
      exit 0
    fi
    o=$(_info owner); p=$(_info pid); s=$(_info since); t=$(_info ttl_min)
    # держатель умер -- снимаем. Именно поэтому держателем пишется PID СЕРВЕРА, а не обёртки:
    # обёртка исчезает после exec, и по ней liveness проверять нельзя.
    if [ -n "${p:-}" ] && ! kill -0 "$p" 2>/dev/null; then
      echo "[слот] держатель $o (pid $p) мёртв -- снимаю замок" >&2; rm -rf "$L"; continue
    fi
    age=$(( ( $(date +%s) - ${s:-0} ) / 60 ))
    if [ "$age" -gt "${t:-45}" ]; then
      echo "[слот] $o просрочил ($age мин > ${t} мин) -- снимаю замок" >&2; rm -rf "$L"; continue
    fi
    [ $(( i % 6 )) -eq 1 ] && echo "[слот] ждём: держит $o ($(_info why)), $age мин" >&2
    sleep 10
  done
  echo "[слот] НЕ ДОЖДАЛСЯ за 2 часа" >&2; exit 1;;
release)
  o=$(_info owner)
  if [ "$o" = "${2:?нужно имя}" ] || [ -z "${o:-}" ]; then rm -rf "$L"; echo "[слот] отдан" >&2
  else echo "[слот] ОТКАЗ: держит $o, а не $2" >&2; exit 1; fi;;
*)
  if [ -d "$L" ]; then
    cat "$L/info" 2>/dev/null
    s=$(_info since); echo "держится $(( ($(date +%s) - ${s:-0}) / 60 )) мин"
    p=$(_info pid); kill -0 "${p:-0}" 2>/dev/null && echo "держатель ЖИВ" || echo "держатель МЁРТВ (замок снимется сам)"
  else echo "СВОБОДЕН"; fi
  nvidia-smi --query-gpu=index,memory.used,memory.total --format=csv,noheader 2>/dev/null | head -2;;
esac
