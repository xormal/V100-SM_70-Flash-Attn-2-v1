#
# ЧТО ЛОВИТ. Генерация со спекуляцией останавливается ровно там, где сумма
# (вход + выход) достигает кратного block_size: `finish_reason` приходит `stop`, то есть
# сервер сообщает о нормальном завершении, а текст оборван посреди слова. Потолок выдачи
# при этом далеко не достигнут.
#
# ПОЧЕМУ ПОД НАГРУЗКОЙ. Без фоновых запросов (батч = 1) дефект НЕ воспроизводится: лечение
# границы срабатывает. При батче > 1 `num_computed_tokens_cpu` при асинхронном планировании
# отстаёт, узкое окно проверки промахивается мимо границы -- и обрыв возвращается. Поэтому
# гейт ОБЯЗАН гнать фоновую нагрузку: без неё он зелёный на сломанной сборке.
#
# ЗАПУСК:  python3 tools/gejt_granicy_bloka.py [порт] [--bez-nagruzki]
# ВЫХОД:   0 -- обрывов нет; 1 -- дефект воспроизвёлся (в журнале видно, на какой сумме).
import json, subprocess, sys, threading, time, urllib.request

ПОРТ = sys.argv[1] if len(sys.argv) > 1 else "8085"
# ЧИСЛО ПРОГОНОВ. Пяти НЕ ХВАТАЕТ: на пяти прогонах сборка с лечением дала 2 обрыва,
# а БЕЗ лечения -- 1, то есть различить их нельзя. Дефект случаен по таймингам батча,
# поэтому гейт обязан быть статистическим, а не единичным.
ПРОГОНОВ = int(next((a.split("=")[1] for a in sys.argv if a.startswith("--прогонов=")), 20))
БЕЗ_НАГРУЗКИ = "--bez-nagruzki" in sys.argv
ТЕМП0 = "--temp0" in sys.argv
БАЗА = f"http://127.0.0.1:{ПОРТ}"
МОДЕЛЬ = __import__("os").environ.get("FA2SM70_GEJT_MODEL", "Qwen3.6-27B-AWQ")
ЦВЕТА = ["ЖЁЛТЫЙ", "СИНИЙ", "ЗЕЛЁНЫЙ", "КРАСНЫЙ", "ЧЁРНЫЙ", "БЕЛЫЙ", "СЕРЫЙ", "ОРАНЖЕВЫЙ"]
НАПОЛНИТЕЛЬ = ("Настоящий раздел содержит служебные сведения о порядке ведения "
               "складского учёта. Записи вносятся в журнал по мере поступления. "
               "Ответственный сотрудник заверяет каждую страницу. Копии хранятся "
               "в архиве организации согласно установленному регламенту. ")

def _зов(путь, тело, таймаут=900):
    з = urllib.request.Request(БАЗА + путь, data=json.dumps(тело).encode(),
                               headers={"Content-Type": "application/json"})
    with urllib.request.urlopen(з, timeout=таймаут) as ф:
        return json.load(ф)

def _токенов(текст):
    return _зов("/tokenize", {"model": МОДЕЛЬ, "prompt": текст}, 300)["count"]

_стоп = threading.Event()

def _фон():
    """Фоновая нагрузка: без неё батч равен единице и дефект не проявляется."""
    i = 0
    while not _стоп.is_set():
        i += 1
        try:
            _зов("/v1/chat/completions",
                 {"model": МОДЕЛЬ, "max_tokens": 80, "temperature": 0.3,
                  "messages": [{"role": "user", "content": f"Расскажи про число {i} в двух предложениях."}]},
                 120)
        except Exception:
            pass
        time.sleep(2)

def main():
    на_блок = _токенов(НАПОЛНИТЕЛЬ)
    блоки = [НАПОЛНИТЕЛЬ] * max(16, 8000 // max(1, на_блок))
    for i in range(8):
        поз = min(len(блоки) - 1, int(len(блоки) * ((i + 0.5) / 8)))
        блоки.insert(поз, f"\n\nВАЖНО: кодовое слово склада номер {i+1} — {ЦВЕТА[i]}-{4100+i*137}.\n\n")
    # [СДВИГ, 04.09] Гейт обязан отличать ГРАНИЦУ БЛОКА от совпадения длин: ответ с 7 из 8
    # складов короче полного на ~22 токена, и на промпте 8090 он даёт сумму ровно 8192.
    # Сдвиг промпта разводит эти два объяснения: граница стоит на месте, длина ответа едет.
    сдвиг_ткн = 0
    for а in sys.argv[1:]:
        if а.startswith("--сдвиг="):
            сдвиг_ткн = int(а.split("=", 1)[1])
    вопрос = ("\n\nВопрос. Выше по тексту встречались кодовые слова складов. Перечисли ВСЕ 8 "
              "из них в формате «склад N — КОД», по одному на строку. Ничего не добавляй.")
    промпт = "".join(блоки) + вопрос
    if сдвиг_ткн:
        промпт = ("слово " * сдвиг_ткн) + промпт

    потоки = []
    if not БЕЗ_НАГРУЗКИ:
        for _ in range(3):
            т = threading.Thread(target=_фон, daemon=True); т.start(); потоки.append(т)
        time.sleep(5)
    обрывов = 0
    полных = 0
    try:
        for i in range(ПРОГОНОВ):
            о = _зов("/v1/chat/completions",
                     {"model": МОДЕЛЬ, "max_tokens": 400,
                      # [04.09] Разброс температуры был ЧАСТЬЮ ПРИБОРА: он ловит
                      # неустойчивость. Но когда меряется ТОЧНОСТЬ пути, он мешает --
                      # рычаг --temp0 убирает его и оставляет чистый детерминизм.
                      "temperature": 0.0 if ТЕМП0 else 0.02 * (i % 5),
                      "messages": [{"role": "user", "content": промпт}]})
            u, c = о["usage"], о["choices"][0]
            текст = c["message"]["content"] or ""
            всего = u["total_tokens"]
            # расстояние до ближайшего кратного 4096 -- признак посадки на границу
            м = всего % 4096
            до = м if м <= 2048 else м - 4096
            найдено = sum(1 for цв in ЦВЕТА if цв in текст)
            # [ОКНО ПРИЗНАКА РАСШИРЕНО 08.09] Стояло `abs(до) <= 1`, и гейт был СЛЕП:
            # на боевом обрыв садится на +2, на стенде -- на +3..+6 (сеть успевает
            # дописать несколько знаков после перехода, прежде чем решение об остановке
            # испортится). Замер с прежним окном: «обрывов 0/20» при ПЯТИ прогонах с
            # потерянной иглой и выдачей 105-108 вместо 124 -- то есть зелёный гейт на
            # сломанной сборке, ровно тот отказ прибора, о котором предупреждает записка.
            # Окно 0..16 вперёд: обрыв -- это остановка ПОСЛЕ перехода, до него причины нет.
            обрыв = 0 <= до <= 16 and c["finish_reason"] == "stop" and найдено < 8
            обрывов += обрыв
            полных += (найдено == 8)
            print(f"  вход={u['prompt_tokens']} выход={u['completion_tokens']:>4} сумма={всего:>5} "
                  f"до кратного={до:>+4} finish={c['finish_reason']:<7} найдено={найдено}/8 "
                  f"{'ОБРЫВ' if обрыв else 'ок'}", flush=True)
    finally:
        _стоп.set()
    print(f"  ИТОГ: полных ответов 8/8: {полных}/{ПРОГОНОВ}; "
          f"обрывов {обрывов}/{ПРОГОНОВ} ({обрывов/ПРОГОНОВ*100:.0f} %) "
          f"({'нагрузка есть' if not БЕЗ_НАГРУЗКИ else 'БЕЗ нагрузки -- гейт ослаблен'})")
    return 1 if обрывов else 0

if __name__ == "__main__":
    sys.exit(main())
