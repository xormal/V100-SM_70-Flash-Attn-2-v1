"""РАЗЛОЖЕНИЕ ЯДРА РОЛЕЙ ПО ФАЗАМ, РАЗДЕЛЬНО ПО РОЛЯМ, ДЛЯ ДВУХ ВАРИАНТОВ СРАЗУ.

ЗАЧЕМ. Когда правка ускоряет счётчик и замедляет секундомер, вопрос «куда переехало» решается не
рассуждением, а разложением периода. Прибор вшит в ядро (`FA2_PHASE`, clock64 по фазам) и разведён
по ролям: везущие пишут со смещением 8, иначе ОЖИДАНИЕ одной группы складывается с РАБОТОЙ другой
и читается как цена работы.

ЧИТАТЬ ТОЛЬКО ПРОПОРЦИИ ВНУТРИ ОДНОГО СТОЛБЦА. Сборка с замером медленнее боевой (clock64 и
атомарные сложения сами стоят), поэтому её миллисекунды с боевыми НЕ СРАВНИВАЮТСЯ.

[ЛОВУШКА, НА КОТОРУЮ Я НАСТУПИЛ 16.08.2026] FA2SM70_PHASE=1 обязан стоять И ПРИ СБОРКЕ, И ПРИ
КАЖДОМ ЗАПУСКЕ. Сборщик torch перестраивает расширение, когда набор флагов не совпал с
закэшированным, -- то есть прогон ЭТОГО инструмента без переменной МОЛЧА пересобирает .so без
замера и стирает прибор, который сам же и собирался читать. Признак: `fa2_phase_read_reset`
исчезает из модуля, а .so датируется временем запуска инструмента, а не сборки.

    export FA2SM70_PHASE=1 FA2SM70_BUILD_DIR=<отдельная>     # ОБА шага под одним окружением
    python -c "import fa2_sm70; fa2_sm70._ext.prefill_ext()"
    python tools/fazy_ws.py [--sk 16384] [--nosc 0,700]

================== ЗАМЕРЕНО 16.08.2026 (Sq=4096, Sk=16384, H=24, Hkv=4, d=256) ==================
                                 база nosc=0   расщепление по ключам nosc=700
  СЧИТАЮЩИЕ  подача Q/K + 1-е умнож.  45.4 %        47.3 %
             маска+максимум+СВОД      40.5 %        37.4 %   <-- свода здесь БОЛЬШЕ НЕТ ВОВСЕ
             exp2 и запись P           7.2 %         6.7 %
             свод сумм + 2-е умнож.    6.0 %         4.3 %
  ВЕЗУЩИЕ    ОЖИДАНИЕ рандеву         54.6 %        27.4 %

ГЛАВНОЕ ЧИСЛО -- 40.5 -> 37.4. У правой колонки ОБА межварповых свода СНЯТЫ (нет ни записи в
sRedM/sRedS, ни барьера, ни сбора по варпам), и фаза просела на ТРИ ПУНКТА. Значит прежнее чтение
«38.9 % тактов считающих -- это сведение» было ошибкой АТРИБУЦИИ: в одну фазу сложены поэлементный
проход маски с максимумом и ОЖИДАНИЕ накопителя S, а свод -- малая их часть. Это ровно тот класс
ошибки, от которого страхует разведение накопителей по ролям, только на уровень глубже: разводить
надо было ещё и предметы ВНУТРИ фазы 3.

СРАВНИВАТЬ КОЛОНКИ ПО СУММЕ ТАКТОВ НЕЛЬЗЯ: 138.65 против 215.04 миллиардов -- это цена самого
прибора, которая у вариантов РАЗНАЯ (у расщепления расписание плотнее, и вставленные clock64
стоят ему дороже). Секундомер на чистой сборке даёт x0.905..0.945, а не x0.64.
"""
import argparse
import os
import sys

import torch

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "benchmarks"))
import fa2_sm70  # noqa: E402
from bench_kspl import кв, таблица_масштабов  # noqa: E402

# Смысл фаз задан вызовами PH(i) в volta_fwd_ws.cuh; у ролей он РАЗНЫЙ, и это не оплошность,
# а устройство: одна и та же точка периода у везущего -- ожидание, у считающего -- работа.
СЧИТАЮЩИЕ = ["0 барьер входа", "1 (не исп.)", "2 подача Q/K + 1-е умнож.",
             "3 маска+максимум+свод", "4 exp2 и запись P", "5 свод сумм + 2-е умнож.",
             "6 (резерв)", "7 (резерв)"]
ВЕЗУЩИЕ = ["0 после рандеву", "1 ОЖИДАНИЕ рандеву", "2 перекладка K/V",
           "3 (резерв)", "4 (резерв)", "5 (резерв)", "6 (резерв)", "7 (резерв)"]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--sk", type=int, default=16384)
    ap.add_argument("--sq", type=int, default=4096)
    ap.add_argument("--nosc", default="0,700")
    ap.add_argument("--fmt", type=int, default=0)
    a = ap.parse_args()
    if os.environ.get("FA2SM70_PHASE") != "1":
        print("FA2SM70_PHASE не выставлена: этот запуск ПЕРЕСОБРАЛ БЫ расширение без замера "
              "и стёр бы прибор. Выставить и повторить."); return 2
    ext = fa2_sm70._ext.prefill_ext()
    if not hasattr(ext, "fa2_phase_read_reset"):
        print("сборка БЕЗ FA2_PHASE -- прибора нет, вердикта нет"); return 2
    D, H, HKV = 256, 24, 4
    torch.manual_seed(0)
    Q = (torch.randn(1, a.sq, H, D, device="cuda") * 4.0).half()
    K = (torch.randn(1, a.sk, HKV, D, device="cuda") * 0.5).half()
    V = (torch.randn(1, a.sk, HKV, D, device="cuda") * 0.5).half()
    Kq, Ks, _a, _b = кв(K, a.sk, D)
    Vq, Vs, _c, _d = кв(V, a.sk, D)
    Kt, Vt = таблица_масштабов(a.fmt, Ks, Vs, a.sk)
    м = 1.0 / (D ** 0.5)
    столбцы = []
    for n in [int(x) for x in a.nosc.split(",")]:
        for _ in range(2):     # прогрев, чтобы в счётчик не попал первый запуск
            ext.attn_fwd_volta_i8(Q, Kq.unsqueeze(0), Kt.unsqueeze(0), Vq.unsqueeze(0),
                                  Vt.unsqueeze(0), м, True, n)
        torch.cuda.synchronize(); ext.fa2_phase_read_reset()
        for _ in range(3):
            ext.attn_fwd_volta_i8(Q, Kq.unsqueeze(0), Kt.unsqueeze(0), Vq.unsqueeze(0),
                                  Vt.unsqueeze(0), м, True, n)
        torch.cuda.synchronize()
        столбцы.append((n, ext.fa2_phase_read_reset().cpu().tolist()))

    сч = [sum(в[:8]) for _, в in столбцы]
    вз = [sum(в[8:]) for _, в in столбцы]
    print(f"\nSq={a.sq} Sk={a.sk} H={H} Hkv={HKV} d={D}, причинная, формат {a.fmt}")
    print(f"{'фаза':<30s}" + "".join(f"{'nosc=' + str(n):>18s}" for n, _ in столбцы))
    print("-- СЧИТАЮЩИЕ (доля тактов роли) --")
    for i, имя in enumerate(СЧИТАЮЩИЕ):
        стр = "".join(f"{(в[i] / с if с else 0):>17.1%} " for (_, в), с in zip(столбцы, сч))
        if any(в[i] for _, в in столбцы):
            print(f"{имя:<30s}{стр}")
    print("-- ВЕЗУЩИЕ (доля тактов роли) --")
    for i, имя in enumerate(ВЕЗУЩИЕ):
        стр = "".join(f"{(в[8 + i] / з if з else 0):>17.1%} " for (_, в), з in zip(столбцы, вз))
        if any(в[8 + i] for _, в in столбцы):
            print(f"{имя:<30s}{стр}")
    print(f"{'ТАКТОВ ВСЕГО (счит.+вез.)':<30s}"
          + "".join(f"{(с + з) / 1e9:>17.2f}м " for с, з in zip(сч, вз)))
    print(f"{'  из них считающие':<30s}"
          + "".join(f"{с / (с + з):>17.1%} " for с, з in zip(сч, вз)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
