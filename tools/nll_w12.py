"""ПРАВДОПОДОБИЕ ФИКСИРОВАННОГО ТЕКСТА -- прибор для оценки ВОЗМУЩЕНИЯ ВЕСОВ.

ЗАЧЕМ ОН ПОНАДОБИЛСЯ. Приёмка «совпал ли текст при T=0» оказалась НЕДЕЙСТВИТЕЛЬНОЙ: два
ОДИНАКОВЫХ запроса к ОДНОМУ серверу расходятся на символе 482 (замерено). Причина -- порядок
сведения в свёртках зависит от состава пачки, а траектория выбора при жадном декоде хаотична: на
«лезвии» (двух почти равных логитах) любой шум последнего разряда переключает токен, и дальше тексты
разъезжаются. Значит эталон сам не воспроизводится, и сравнивать с ним нельзя.

ЧТО МЕРЯЕТСЯ ВМЕСТО. Средний -log P на токен ФИКСИРОВАННОГО текста: модель не выбирает ничего, мы
читаем её распределение. Это среднее по тысячам токенов, поэтому шум последнего разряда усредняется,
а систематический сдвиг от возмущения весов -- нет. Собственный шум прибора замеряется повтором В
ТОЙ ЖЕ конфигурации, и вердикт выносится ТОЛЬКО если разница конфигураций больше этого шума.

ДВА ТЕКСТА, И ЭТО ИСПРАВЛЕНИЕ ПРИБОРА. Первая редакция брала ОДИН абзац, повторённый двенадцать
раз, и дала разницу 8.75 % между конфигурациями при нулевом собственном шуме. Такой величины от
возмущения весов в 4e-04 быть не может -- значит мерилось не то. На повторяющемся тексте почти
каждый токен предсказуем ИЗ ПОВТОРА, то есть прибор мерит КОПИРОВАНИЕ; а копирование живёт ровно в
тех головах внимания, чьи проекции мы и трогаем. Вывод по такому тексту недействителен для вопроса
«испортилась ли модель».
Поэтому текстов ДВА: естественный (непоследовательный, из документа проекта) -- он и есть вердикт;
и повторяющийся -- он оставлен НАМЕРЕННО, как отдельный замер способности копировать.

    python tools/nll_w12.py <порт> [повторов]
"""
import json
import statistics
import sys
import urllib.request

ТЕКСТ = ("Пропускная способность памяти видеокарты определяет, насколько быстро вычислительные "
         "блоки получают данные. Когда ядро читает каждый байт ровно один раз и не переиспользует "
         "загруженное, время работы задаётся не арифметикой, а потоком из памяти. Поэтому у таких "
         "ядер единственный рычаг -- сократить объём чтения либо сделать поток ровнее. "
         "Иерархия памяти состоит из регистров, разделяемой памяти блока, кэша первого уровня, "
         "общего кэша второго уровня и внешней памяти устройства. Каждая ступень вниз даёт "
         "примерно на порядок больший объём и на порядок большую задержку. "
         "Арифметическая интенсивность -- отношение числа операций к числу прочитанных байт -- "
         "определяет, в какую часть кровельной диаграммы попадает задача. ") * 12


def естественный(символов=9000):
    """Непоследовательная проза из документа проекта. Один и тот же срез в обеих конфигурациях."""
    import os
    ф = os.path.join(os.path.dirname(__file__), "..", "docs", "VOLTA_SM70.md")
    с = open(ф, encoding="utf-8").read()
    return с[2000:2000 + символов]


def нll(порт, имя, текст):
    тело = json.dumps({"model": имя, "prompt": текст, "max_tokens": 1, "temperature": 0.0,
                       "echo": True, "logprobs": 0}).encode()
    зпр = urllib.request.Request(f"http://127.0.0.1:{порт}/v1/completions", data=тело,
                                 headers={"Content-Type": "application/json"})
    with urllib.request.urlopen(зпр, timeout=900) as о:
        д = json.loads(о.read())
    лп = [x for x in д["choices"][0]["logprobs"]["token_logprobs"] if x is not None]
    return -sum(лп) / len(лп), len(лп)


def main():
    порт = int(sys.argv[1]); повторов = int(sys.argv[2]) if len(sys.argv) > 2 else 3
    with urllib.request.urlopen(f"http://127.0.0.1:{порт}/v1/models", timeout=60) as о:
        имя = json.loads(о.read())["data"][0]["id"]
    for метка, текст in (("ЕСТЕСТВЕННЫЙ (вердикт)", естественный()),
                         ("повторяющийся (копирование)", ТЕКСТ)):
        з = [нll(порт, имя, текст) for _ in range(повторов)]
        зн = [x[0] for x in з]
        print(f"{метка:30s} токенов {з[0][1]:>5d}  -logP/токен {statistics.mean(зн):.6f}  "
              f"разброс {max(зн)-min(зн):.2e}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
