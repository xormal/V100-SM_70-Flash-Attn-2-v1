"""ПРИЁМКА ВЕСОВ int12 СКВОЗЬ СЕРВЕР. Пишет снимок в файл; сравнение -- отдельным прогоном.

ПОЧЕМУ ДЛИННАЯ ГЕНЕРАЦИЯ, А НЕ ДЕСЯТЬ КОРОТКИХ ВОПРОСОВ. Прежний харнесс рапортовал 10/10 даже
пути, огрублённому в 79 раз: на 5-10 токенах ответ вырожден и расхождение не успевает проявиться.
Зубы приёмке даёт ДЛИНА -- при 768 токенах при T=0 любое смещение логита рано или поздно меняет
выбранный токен, и дальше расхождение только растёт.

ЧТО СРАВНИВАЕТСЯ. Побитово -- сам текст. Совпадение текста на 768 токенах при T=0 это не «похоже»,
это тождество траектории выбора. Плюс скорость: ток/с считается ПО ОТВЕТУ СЕРВЕРА (usage), а не по
стенным часам клиента, иначе меряется сеть.

    python tools/priem_w12.py <порт> <файл-снимка>
    python tools/priem_w12.py --сверить <а.json> <б.json>
"""
import json
import sys
import time
import urllib.request

ЗАДАНИЯ = [
    ("столица", "Назови столицу Франции одним словом.", 8),
    ("озеро", "Какое озеро самое большое по площади в мире? Ответь одним словом.", 8),
    ("длинный-1", "Объясни подробно, как работает механизм внимания в трансформере: "
                  "запросы, ключи, значения, softmax, многоголовость, маскирование.", 768),
    ("длинный-2", "Напиши подробное пошаговое решение: как найти все простые числа до 1000 "
                  "решетом Эратосфена, и объясни сложность.", 768),
    ("длинный-3", "Опиши устройство иерархии памяти видеокарты и почему пропускная способность "
                  "часто важнее пиковой арифметики.", 768),
]


_ИМЯ = {}


def имя_модели(порт):
    """Имя берётся У СЕРВЕРА. Зашитая строка ('qwen') дала 404 -- слепок отдаётся под своим id."""
    if порт not in _ИМЯ:
        with urllib.request.urlopen(f"http://127.0.0.1:{порт}/v1/models", timeout=60) as о:
            _ИМЯ[порт] = json.loads(о.read())["data"][0]["id"]
    return _ИМЯ[порт]


def спросить(порт, промпт, максток):
    тело = json.dumps({
        "model": имя_модели(порт), "prompt": промпт, "max_tokens": максток,
        "temperature": 0.0, "top_p": 1.0, "seed": 0,
    }).encode()
    зпр = urllib.request.Request(f"http://127.0.0.1:{порт}/v1/completions", data=тело,
                                 headers={"Content-Type": "application/json"})
    t0 = time.perf_counter()
    with urllib.request.urlopen(зпр, timeout=1200) as о:
        д = json.loads(о.read())
    стена = time.perf_counter() - t0
    вых = д["usage"]["completion_tokens"]
    return д["choices"][0]["text"], вых, вых / стена


def снять(порт, куда, длина=0, раундов=1):
    """длина>0 переопределяет max_tokens.

    ЗАЧЕМ ДЛИННЕЕ. При 768 токенах разброс ток/с между раундами вышел +-7 % при ожидаемом эффекте
    ~2 % -- прибор НЕ РАЗРЕШАЕТ то, что меряет, и любой вердикт по нему недействителен. Постоянная
    часть (HTTP, планирование, префилл) не зависит от длины, поэтому она разбавляется ростом длины;
    берётся МЕДИАНА ПО РАУНДАМ, а не один снимок.
    """
    сн = {}
    for имя, п, mt in ЗАДАНИЯ:
        mt = длина if (длина and mt > 64) else mt
        замеры = [спросить(порт, п, mt) for _ in range(раундов if mt > 64 else 1)]
        замеры.sort(key=lambda z: z[2])
        текст, ток, скор = замеры[len(замеры) // 2]
        сн[имя] = {"текст": текст, "токенов": ток, "ток_с": скор,
                   "все": [round(z[2], 2) for z in замеры]}
        print(f"  {имя:12s} {ток:>5d} ток  медиана {скор:>5.2f} ток/с  из {[z[2] for z in замеры]}"
              .replace("[", "[").replace("'", ""))
    json.dump(сн, open(куда, "w"), ensure_ascii=False, indent=1)
    print(f"снимок -> {куда}")


def сверить(a, b):
    A, B = json.load(open(a)), json.load(open(b))
    расх = 0
    print(f"{'задание':12s} {'текст':>12s} {'ток/с A':>8s} {'ток/с B':>8s} {'B/A':>6s}")
    for k in A:
        ok = A[k]["текст"] == B[k]["текст"]
        расх += not ok
        print(f"{k:12s} {'СОВПАЛ' if ok else 'РАЗОШЁЛСЯ':>12s} "
              f"{A[k]['ток_с']:>8.1f} {B[k]['ток_с']:>8.1f} {B[k]['ток_с']/A[k]['ток_с']:>6.3f}")
        if not ok:
            # ГДЕ разошлось -- важнее ЧТО: расхождение с первого токена и на 600-м это разные дефекты
            t1, t2 = A[k]["текст"], B[k]["текст"]
            i = next((j for j in range(min(len(t1), len(t2))) if t1[j] != t2[j]), min(len(t1), len(t2)))
            print(f"             первое различие на символе {i} из {len(t1)}")
    длин = [k for k in A if k.startswith("длинный")]
    ср = sum(B[k]["ток_с"] / A[k]["ток_с"] for k in длин) / len(длин)
    print(f"\nрасхождений {расх} из {len(A)}; скорость на длинных x{ср:.3f}")
    return 1 if расх else 0


def _главная():
    if sys.argv[1] == "--префилл":
        префилл(int(sys.argv[2]))
        return 0
    if sys.argv[1] == "--сверить":
        return сверить(sys.argv[2], sys.argv[3])
    снять(sys.argv[1], sys.argv[2],
          длина=int(sys.argv[3]) if len(sys.argv) > 3 else 0,
          раундов=int(sys.argv[4]) if len(sys.argv) > 4 else 1)
    return 0


# --- ПРЕФИЛЛ ----------------------------------------------------------------------------------
# Мерится ОТДЕЛЬНО, потому что рычаг действует на две фазы ПО-РАЗНОМУ: декоду он режет байты, а
# префиллу ДОБАВЛЯЕТ проход распаковки. Нельзя проверить одно и объявить про оба.
# Промпт МЕНЯЕТСЯ на каждом повторе: префикс-кэш включён, и повтор того же текста измерил бы кэш.
def префилл(порт, слов=24000, повторов=3):
    import statistics
    т = []
    for i in range(повторов):
        п = (f"Документ номер {i}. " + "Волга впадает в Каспийское море. " * (слов // 5))
        t0 = time.perf_counter()
        спросить_сырой(порт, п)
        т.append(time.perf_counter() - t0)
    print(f"  префилл ~{слов} слов: медиана {statistics.median(т):.2f} с  из "
          f"{[round(x, 2) for x in т]}")
    return statistics.median(т)


def спросить_сырой(порт, промпт):
    тело = json.dumps({"model": имя_модели(порт), "prompt": промпт, "max_tokens": 1,
                       "temperature": 0.0}).encode()
    зпр = urllib.request.Request(f"http://127.0.0.1:{порт}/v1/completions", data=тело,
                                 headers={"Content-Type": "application/json"})
    with urllib.request.urlopen(зпр, timeout=1800) as о:
        return json.loads(о.read())


if __name__ == "__main__":
    sys.exit(_главная())
