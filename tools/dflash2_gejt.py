#!/usr/bin/env python3
"""ГЕЙТ ХАРНЕССА ЧЕРНОВИКА: воспроизводит ли офлайн-путь то, что черновик делает В БОЮ.

ЗАЧЕМ ОН ГЛАВНЕЕ ОБУЧЕНИЯ. Прежние заходы учили черновик в харнессе, который давал 1-4 %
на позиции 0 там, где бой даёт 54-77 %. Учить в приборе, не воспроизводящем бой, -- значит
днями оптимизировать НЕ ТУ функцию. Поэтому порядок жёсткий: сперва базовый (необученный)
черновик обязан показать здесь свою боевую точность, и только после этого что-то учится.

ЧЕМ ЭТОТ ПРИБОР ОТЛИЧАЕТСЯ ОТ ПРЕЖНИХ ТРЁХ.
  1. Признаки СЫРЫЕ (25600, пять слоёв цели) и проходят через `fc` -- ровно как в бою;
     прежде в `kv_контекста` подавались состояния 5120, то есть ВЫХОД fc выдавался за ВХОД.
  2. Цепочка режется по ПОЗИЦИЯМ: склейка через границу запросов давала черновику чужой
     контекст (одна пара из десяти).
  3. Сдвиг метки явный: логиты цели на позиции j -- это распределение токена j+1.
  4. Длина контекста -- ось свипа, а не константа 8/32: в бою впрыснут ВЕСЬ префикс.

ЗАПУСК:  KONTEKST=256 PROB=200 python3 dflash2_gejt.py /mnt/d1/alex/dflash2_syryo
"""
import os, sys, glob, json, time
import torch

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                "..", "integrations", "vllm_sm70"))
from dflash2.telo_polnoe import ЧерновикDFlash2
from dflash2.otbor import отобрать_по_префиксу

ЦЕЛЬ = "/mnt/d1/alex/VLLM_ch/Qwen3.8-27B-ABL_int8_i12"


def торч_тип_головы(тип):
    """Голова 248320x5120: в fp32 это 5 ГБ. Держим её в fp16 всегда -- она ЗАМОРОЖЕНА, а
    умножение всё равно приводится к типу состояния."""
    return torch.float16


def тензор_цели(имя, dev, тип=torch.float16):
    from safetensors.torch import safe_open
    idx = json.load(open(os.path.join(ЦЕЛЬ, "model.safetensors.index.json")))
    with safe_open(os.path.join(ЦЕЛЬ, idx["weight_map"][имя]), framework="pt", device="cpu") as f:
        return f.get_tensor(имя).to(dev, тип)


def строка_цели(имя, i, dev, тип=torch.float16):
    from safetensors.torch import safe_open
    idx = json.load(open(os.path.join(ЦЕЛЬ, "model.safetensors.index.json")))
    with safe_open(os.path.join(ЦЕЛЬ, idx["weight_map"][имя]), framework="pt", device="cpu") as f:
        return f.get_tensor(имя)[i].to(dev, тип)


def цепочка(корпус, предел, вернуть_логиты=False):
    """Связные отрезки корпуса: (признаки[N,F], токен_следующий[N], границы отрезков)."""
    Ф, Т, П, ЗН, ИД, ТК = [], [], [], [], [], []
    # ПРОПУСК ФАЙЛОВ. Обучение берёт корпус С НАЧАЛА (PREDEL токенов), поэтому гейт,
    # читающий тоже с начала, меряет на ОБУЧАЮЩИХ данных и показывает переобучение как приз.
    # PROPUSK сдвигает окно за обученную часть.
    _пропуск = int(os.environ.get("PROPUSK", "0"))
    for ф in sorted(glob.glob(os.path.join(корпус, "*.pt")))[_пропуск:]:
        try:
            пары = torch.load(ф, map_location="cpu")
        except Exception:
            continue
        for п in пары:
            if len(п) < 3:
                continue
            приз, метка, m = п[0], п[1], int(п[2])
            поз = п[3] if len(п) > 3 else None
            m = max(1, min(m, приз.shape[0]))
            топ1 = (метка[1][:, 0] if isinstance(метка, tuple) else метка.reshape(-1))
            # Позиции у мультимодальной цели приходят В ТРИ РЯДА (M-RoPE); текстовый ряд --
            # нулевой, остальные два для нашей задачи копии. Берём ряд 0, а не «первые m».
            if поз is not None and поз.dim() > 1:
                поз = поз[0]
            Ф.append(приз[:m]); Т.append(топ1[:m].long())
            # НАСТОЯЩИЕ токены позиций (сбор идёт при температуре 0.7, и жадный top-1 цели
            # расходится с тем, что она выбрала на самом деле; признаки взяты из НАСТОЯЩЕЙ
            # цепочки, значит и бонусный токен, и метки обязаны быть из неё же).
            ток = п[4] if len(п) > 4 else None
            ТК.append(ток[:m].long() if ток is not None else топ1[:m].long())
            if вернуть_логиты and isinstance(метка, tuple):
                ЗН.append(метка[0][:m]); ИД.append(метка[1][:m])
            П.append(поз[:m].long() if поз is not None
                     else torch.full((m,), -1, dtype=torch.long))
        if sum(x.shape[0] for x in Ф) >= предел:
            break
    if not Ф:
        return (None, None, None, []) if вернуть_логиты else (None, None, [])
    Ф = torch.cat(Ф); Т = torch.cat(Т); П = torch.cat(П); ТК = torch.cat(ТК)
    # Разрыв там, где позиция не продолжает предыдущую: это ГРАНИЦА ЗАПРОСА.
    разрывы = [0] + (torch.nonzero(П[1:] != П[:-1] + 1).flatten() + 1).tolist() + [len(П)]
    отрезки = [(разрывы[i], разрывы[i + 1]) for i in range(len(разрывы) - 1)]
    if вернуть_логиты:
        ЛОГ = (torch.cat(ЗН), torch.cat(ИД)) if ЗН else None
        return Ф, ТК, ЛОГ, отрезки
    return Ф, ТК, отрезки


def main():
    корпус = sys.argv[1] if len(sys.argv) > 1 else "/mnt/d1/alex/dflash2_syryo"
    ЧЕРН = os.environ.get("CHERN", "/mnt/d1/alex/Qwen3.8-27B-DFlash2")
    L = int(os.environ.get("KONTEKST", "256"))
    проб = int(os.environ.get("PROB", "200"))
    k = int(os.environ.get("SPEC_K", "3"))
    сдвиг = int(os.environ.get("SDVIG", "0"))
    ПРОХОДОВ = int(os.environ.get("PROHODOV", "1"))
    _з = os.environ.get("ZAMEN", "1")
    ЗАМЕН = -1 if _з == "auto" else int(_з)
    ЧИТАТЬ = os.environ.get("CHITAT", "maska")
    ОРАКУЛ = int(os.environ.get("ORAKUL", "0"))
    предел = int(os.environ.get("PREDEL", "40000"))
    torch.manual_seed(int(os.environ.get("SEED", "20260908")))
    dev = "cuda"

    Ф, Т, отрезки = цепочка(корпус, предел)
    if Ф is None:
        print("корпус пуст"); return
    годные = [(a, b) for a, b in отрезки if b - a >= L + k + 6]
    print(f"  корпус: {Ф.shape[0]} токенов, признаки {Ф.shape[1]}, "
          f"отрезков {len(отрезки)} (годных под L={L}: {len(годные)})")
    if not годные:
        print("  ни одного отрезка длиннее контекста -- уменьшите KONTEKST"); return

    from safetensors.torch import load_file
    конф = json.load(open(os.path.join(ЧЕРН, "config.json")))
    # ТИП fp32. В бою поток остатка идёт в fp32 намеренно (`_поток_fp32` в qwen3_dflash2:
    # «иначе NaN»), и это не украшение: после `fc` состояния имеют размах ~7e3, а тело с
    # промежуточным слоем 17408 в fp16 переполняется -- эталон выдавал NaN на КАЖДОЙ пробе,
    # и любая точность в этом приборе была бы нулём независимо от черновика.
    тип = torch.float32 if os.environ.get("TIP", "32") == "32" else torch.float16
    ч = ЧерновикDFlash2(load_file(os.path.join(ЧЕРН, "model.safetensors")),
                        конф, устройство=dev, тип=тип)
    lm = тензор_цели("lm_head.weight", dev, торч_тип_головы(тип))
    idx = json.load(open(os.path.join(ЦЕЛЬ, "model.safetensors.index.json")))
    имя_вл = next(n for n in idx["weight_map"] if n.endswith("embed_tokens.weight"))
    # ВСЯ таблица вложений цели: строка бонусного токена нужна на КАЖДОЙ пробе, а он
    # каждый раз другой. 248320x5120 в fp16 -- 2.5 ГБ, помещается.
    вложения = тензор_цели(имя_вл, dev, torch.float16)
    вл_маски = вложения[ч.маска_id].to(тип)
    print(f"  голова цели {tuple(lm.shape)}, вложение маски |.|max={вл_маски.abs().max():.4g}")
    # Кодбуки отбора в fp32: логиты головы считаются в fp32 (в бою так же -- LogitsProcessor
    # приводит), и einsum отказывается смешивать типы.
    кб_пред = ч.в["candidate_selector.predecessor_codebook"].float()
    кб_прее = ч.в["candidate_selector.successor_codebook"].float()

    точн = [0] * k; преф = [0] * k; сум_приёмки = 0.0; n = 0
    t0 = time.time()
    with torch.no_grad():
        for _ in range(проб):
            a, b = годные[torch.randint(len(годные), (1,)).item()]
            i = torch.randint(a + L, b - k - 3, (1,)).item()
            сыр = Ф[i - L + 1:i + 1].to(dev, тип)
            сост = ч.слить_признаки(сыр)                        # ТА ЖЕ fc, что в бою
            поз_к = torch.arange(L, device=dev)
            K, V = ч.kv_контекста(сост, поз_к)
            kv = [(K[l], V[l], поз_к) for l in range(ч.слоёв)]
            # [РАСКЛАДКА ЗАПРОСА КАК В БОЮ -- 08.09] Запрос черновика это НЕ k маск-токенов,
            # а 1 + k: нулевая строка -- БОНУСНЫЙ токен (тот, что цель только что выдала) с
            # его настоящим вложением и позицией p+1, дальше k масок на p+2..p+k+1. Читаются
            # только маск-строки (`query_off > 0` в ядре раскладки). Прежний прибор подавал
            # только маски -- то есть отнимал у черновика единственный ТОКЕННЫЙ вход и сдвигал
            # все позиции на единицу. Отсюда и была «точность 1-4 %».
            бонус = Т[i + 1].item()      # токен позиции p+1 -- он же вход нулевой строки
            истина0 = Т[i + 2:i + 2 + k]
            # ОРАКУЛ: первые ОРАКУЛ позиций блока раскрыты ИСТИНОЙ. Это ПОТОЛОК решётчатой
            # конструкции: показывает, сколько вообще даёт знание предыдущего токена, если
            # угадывать его не надо. Если потолок низок -- второй проход бесполезен ЛЮБОЙ,
            # и слабость поздних позиций не от незнания соседа.
            _стр = [вложения[бонус][None].to(тип)]
            for j in range(k):
                _стр.append(вложения[int(истина0[j])][None].to(тип) if j < ОРАКУЛ
                            else вл_маски[None])
            вх = torch.cat(_стр, dim=0).contiguous()
            поз_б = torch.arange(L, L + k + 1, device=dev)
            скр_все = ч.проход_блока(вх, поз_б, kv_внеш=kv)
            # [ЧТЕНИЕ СТРОК]. Бой читает строки 1..k (маски): каждая маска предсказывает СВОЮ
            # позицию. Но строка 0 держит НАСТОЯЩИЙ токен позиции p+1 -- и если черновик умеет
            # авторегрессию, её выход это предсказание p+2, которое бой ВЫБРАСЫВАЕТ. Рычаг
            # CHITAT=avto читает строки 0..k-1 вместо 1..k и отвечает на это числом.
            скр = скр_все[:-1] if ЧИТАТЬ == "avto" else скр_все[1:]
            логиты = (скр.to(lm.dtype) @ lm.T).float()
            # [ВТОРАЯ КОНСТРУКЦИЯ: ЧАСТИЧНО АВТОРЕГРЕССИВНЫЙ БЛОК]
            # Блочный черновик предсказывает все k позиций ПАРАЛЛЕЛЬНО: строка j не знает, что
            # выпало строке j-1, и точность падает с 57 % на позиции 0 до 21 % на позиции 2.
            # Здесь блок прогоняется ЕЩЁ РАЗ, но первые `ЗАМЕН` масок заменены токенами,
            # которые он же и предсказал. Контекст (fc + впрыск K/V) считается ОДИН раз, а он
            # и есть дорогая часть -- цена второго прохода это только тело на k+1 строке.
            #   ЗАМЕН=0 -- прежнее поведение до бита;
            #   ЗАМЕН=k -- полная подстановка (модель может выродиться в копирование);
            #   0<ЗАМЕН<k -- решётка: ранние позиции зафиксированы, поздние ещё маски.
            дог = логиты.argmax(-1)
            for _т in range(1, ПРОХОДОВ):
                # ЗАМЕН="auto": на t-м лишнем проходе раскрыто ровно t позиций -- лесенка от
                # параллельного блока к авторегрессии внутри блока. Раскрытые берутся из
                # ПРЕДЫДУЩЕГО прохода и больше не переспрашиваются.
                z = _т if ЗАМЕН < 0 else ЗАМЕН
                стр = [вх[0][None]]
                for j in range(k):
                    стр.append(вложения[int(дог[j])][None].to(тип) if j < z
                               else вл_маски[None])
                вх2 = torch.cat(стр, dim=0).contiguous()
                скр_все = ч.проход_блока(вх2, поз_б, kv_внеш=kv)
                скр = скр_все[:-1] if ЧИТАТЬ == "avto" else скр_все[1:]
                нов = (скр.to(lm.dtype) @ lm.T).float()
                # Раскрытые позиции НЕ переписываем: их ответ уже принят и подан на вход.
                логиты = torch.cat((логиты[:z], нов[z:]), dim=0) if z > 0 else нов
                дог = логиты.argmax(-1)
            истина = Т[i + 2 + сдвиг:i + 2 + сдвиг + k].to(dev)
            top1 = логиты.argmax(-1)
            _цел = True
            for j in range(k):
                точн[j] += int(top1[j].item() == истина[j].item())
                _цел = _цел and (top1[j].item() == истина[j].item())
                преф[j] += int(_цел)
            унар, канд = логиты.topk(ч.к["dflash_config"]["selector_top_k"], dim=-1)
            h_r = скр.float() @ ч.в["candidate_selector.hidden_projection.weight"].float().T
            # Якорь отбора -- БОНУСНЫЙ токен: у боевой позиции 0 предшественник именно он.
            якорь = Т[i + 1].view(1).to(dev)
            ток = отобрать_по_префиксу(кб_пред, кб_прее,
                                       канд[None], унар[None], h_r[None].float(), якорь)[0]
            длина = 1
            for совпал in (ток[:k] == истина[:k]).tolist():
                if совпал: длина += 1
                else: break
            сум_приёмки += длина; n += 1
    стр = "  ".join(f"поз{j}={точн[j] / n * 100:.1f}%" for j in range(k))
    print(f"  L={L} проходов={ПРОХОДОВ} замен={ЗАМЕН} оракул={ОРАКУЛ} проб={n} ({time.time() - t0:.0f} с): {стр}")
    стр2 = "  ".join(f"первых{j + 1}={преф[j] / n * 100:.1f}%" for j in range(k))
    print(f"  ПРЕФИКСЫ (из них и складывается tau): {стр2}")
    print(f"  ОФЛАЙН-ПРИЁМКА tau={сум_приёмки / n:.3f} "
          f"(верхняя оценка по top-1: {1 + sum(преф) / n:.3f})")


if __name__ == "__main__":
    main()
