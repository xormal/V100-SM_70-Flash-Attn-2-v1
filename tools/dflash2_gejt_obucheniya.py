#!/usr/bin/env python3
"""ЧЕСТНЫЙ гейт обучения черновика: приёмка на ВАЛИДАЦИИ, а не на своём корпусе.

ЗАЧЕМ. Обучение тела на 50 тысячах токенов подняло приёмку прибора с 1.265 до 1.498 (+18 %),
а в бою она УПАЛА с 1.5 до 1.42. Разгадка в том, что прибор считает приёмку по цепочке ИЗ
ТОГО ЖЕ корпуса: отложенные 10 % -- те же тексты и тот же домен, поэтому метрика растёт
подгонкой. Замер это подтвердил числом:

    черновик      обучающий корпус   валидация (другие темы)
    базовый             1.263              1.343
    обученный           1.517 (+20 %)      1.353 (+0.7 %)

То есть обобщения НЕТ. Гейт сравнивает две версии на корпусе, которого не было в обучении,
и годным считает прирост именно там.

  БАЗА=<каталог> НОВЫЙ=<каталог> python3 dflash2_gejt_obucheniya.py <валидационный корпус>

Валидационный корпус собирается тем же рычагом, что обучающий (FA2SM70_DFLASH2_DUMP), но на
ЗАВЕДОМО других темах: если домены пересекутся, гейт снова будет мерить подгонку.
"""
import os, subprocess, sys

ВАЛИД = sys.argv[1] if len(sys.argv) > 1 else "/mnt/d1/alex/dflash2_valid"
БАЗА = os.environ.get("BAZA", "/mnt/d1/alex/Qwen3.8-27B-DFlash2")
НОВЫЙ = os.environ.get("NOVYJ", "")
ПОРОГ = float(os.environ.get("POROG", "0.05"))     # требуемый прирост на валидации, доля
_здесь = os.path.dirname(os.path.abspath(__file__))

def приёмка(чернoвик, корпус):
    ср = dict(os.environ, CHERN=чернoвик, PROB=os.environ.get("PROB", "300"))
    вых = subprocess.run([sys.executable, os.path.join(_здесь, "dflash2_priyomka.py"), корпус],
                         capture_output=True, text=True, env=ср).stdout
    for стр in вых.splitlines():
        if "приёмка" in стр:
            return float(стр.split("приёмка")[1].split("(")[0].strip())
    raise RuntimeError(f"прибор не дал числа:\n{вых[-800:]}")

if not НОВЫЙ:
    print("укажите NOVYJ=<каталог обученного черновика>"); sys.exit(2)
б = приёмка(БАЗА, ВАЛИД)
н = приёмка(НОВЫЙ, ВАЛИД)
д = (н - б) / б
print(f"  валидация: база {б:.3f} -> новый {н:.3f}  ({д*100:+.1f} %)")
годен = д >= ПОРОГ
print(f"  ВЕРДИКТ: {'ГОДЕН' if годен else 'НЕ ГОДЕН'} (порог {ПОРОГ*100:+.0f} % на валидации)")
sys.exit(0 if годен else 1)
