//
// ЗАЧЕМ. Замерено (§4qq): Triton при цели sm_70 НЕ ЭМИТИТ тензорных инструкций вообще -- в PTX
// mma.sync 0, wmma 0, hmma 0 и 1024 fma.rn.f32, то есть tl.dot компилируется в цикл FP32-FMA на
// обычных ядрах. Потолок 3.5 TFLOP/s против 83 у cuBLAS и 44 у наших рукописных ядер.
//
// ЧТО СЧИТАЕТСЯ (ровно как в chunk_fwd_kernel_o, чанк BT=64):
//     o[t][v] = scale * ( e^{g_t} * SUM_k q[t][k] h[v][k]
//                       + SUM_{s<=t} e^{g_t - g_s} * (SUM_k q[t][k] k[s][k]) * v[s][v] )
// Три умножения матриц на пару (чанк, голова):
//     G1: b_o[64,128] = q[64,128] x h^T          (h лежит [V][K], k непрерывен -> kKMajor)
//     G2: b_A[64, 64] = q[64,128] x k^T          (k лежит [t][k], k непрерывен -> kKMajor)
//     G3: b_o += tril(b_A)[64,64] x v[64,128]    (v лежит [t][v], v непрерывен -> kNMajor)
//
// =================================================================================================
// ЧЕМ ЭТО ЯДРО ОГРАНИЧЕНО НА САМОМ ДЕЛЕ (посчитано по определению; T=15680, H=Hg=4, BT=64, d=128)
// =================================================================================================
//     перенесено байт .... 96.59 МБ  (q,k,v,o по 16.06 + СОСТОЯНИЕ h 32.11 -- ТРЕТЬ всего трафика)
//     работы ............. 4.110 GFLOP
//     плотность .......... 42.6 FLOP/байт,  точка перелома V100 = 93.6e12/841e9 = 111.3 FLOP/байт
// ПЛОТНОСТЬ ВТРОЕ НИЖЕ ТОЧКИ ПЕРЕЛОМА -> потолок ставит ПАМЯТЬ, а не тензорные ядра:
//     841 ГБ/с (замеренный достижимый, VOLTA_SM70 §2)  ->  0.1148 мс  =  35.8 TFLOP/s   <- ПОТОЛОК
//     93.6 TFLOP/s (потолок HMMA)                      ->  0.0439 мс                    <- недостижим
// Всякая правка меряется против 35.8 TFLOP/s. Это отменяет посылку "запас кратный": запас ровно
// x2.1, и он ВЕСЬ в совмещении подачи со счётом, а не в скорости умножений. Ни одна геометрия
// плитки этого не даст -- переставлять надо не плитку, а РЕЗИДЕНТНОСТЬ.
//
// =================================================================================================
// ЧТО НАЙДЕНО ПЕРЕБОРОМ ГЕОМЕТРИИ (V100, GPU 0, опора меряется вплотную, медиана отношений)
// =================================================================================================
// ЕДИНСТВЕННЫЙ РЫЧАГ -- ВТОРОЙ РЕЗИДЕНТНЫЙ БЛОК. Ядро не имеет мейнлупа: оно грузит ~96 КБ, ставит
// барьер, считает три умножения и выходит. При ОДНОМ блоке на SM подача и счёт СТРОГО ПОСЛЕДОВАТЕЛЬНЫ
// и прятать задержку нечем (VOLTA_SM70 §4: "с 8 варпами перекрывать ожидание нечем"). Второй блок --
// единственное, что даёт перекрытие, и порог у него ДВОЙНОЙ: <= 48 КБ разделяемой И <= 128 регистров.
//
//   * РАЗДЕЛЯЕМАЯ: 77.0 -> 43.0 КБ. Состояние h (34.8 КБ, самый крупный буфер) больше НЕ СТАВИТСЯ в
//     разделяемую -- оно читается ПРЯМО ИЗ ГЛОБАЛЬНОЙ как операнд B (H_DIRECT). Это законно именно
//     здесь: h читается РОВНО ОДИН РАЗ и не переиспользуется ни внутри блока, ни между блоками, так
//     что промежуточная станция в разделяемой не давала ничего, кроме места и лишнего прохода STS.
//   * РЕГИСТРЫ: 210 -> 122 при НУЛЕВОМ разливе. Дала не экономия, а СЕТКА ВАРПОВ 1x8 (плитка варпа
//     64x16) плюс отдельная сетка 2x4 для промежуточной A и слияние накопителя G3 в накопитель G1.
//
// ОТДЕЛЬНАЯ СЕТКА ВАРПОВ ДЛЯ A -- главная находка по форме. У выхода стороны 64x128, у промежуточной
// A -- 64x64; ОДНА сетка не может быть хороша для обеих. Разведя их (выход 1x8, A 2x4), получаем
// 130 регистров вместо 206 при ТОЙ ЖЕ работе -- разбор в §"почему 1x8" ниже.
//
// ЗАМЕРЕНО, T=15680 (980 блоков), отношение к отгруженной геометрии 2x4:
//   геометрия                                   варп  smem   рег  кадр бл/SM   мс     отношение
//   2x4 32x32, h через smem   (ОПОРА)             8   77.0К  210   0    1    0.2174     1.000
//   4x2 16x64                                     8   77.0К  152   0    1    0.2464     0.891
//   1x8 64x16, A=2x4                              8   77.0К  130   0    1    0.2200     0.993
//   1x8 64x16, A=4x2                              8   77.0К  130   0    1    0.2241     0.977
//   2x4 32x32, A=4x2                              8   77.0К  116   0    1    0.2305     0.951
//   4x4 16x32                                    16   77.0К  124   0    1    0.2438     0.900
//   2x8 32x16, A=4x4                             16   77.0К   90   0    1    0.2394     0.916
//   2x2 32x64                                     4   77.0К  255   0    1    0.2652     0.827
//   4x1 16x128                                    4   77.0К  206   0    1    0.2833     0.776
//   1x4 64x32                                     4   77.0К  255  624   1    0.3557     0.616
//   2x4, h ПРЯМО, один блок (210 рег)             8   43.0К  212   0    1    0.2460     0.892
//   1x8, h ПРЯМО, ДВА блока            <- ЭТО     8   43.0К  122   0    2    0.1968     1.105
//   1x8, h ПРЯМО, + sA поверх sQ                  8   34.0К  124   0    2    0.1972     1.095
//   1x8, K и V тоже прямо, ТРИ блока              8   26.0К   80   8    3    0.2243     0.965
//   1x8, четыре блока (64 рег)                    8   17.0К   64  840   4    0.9781     0.222
//
// ЧИТАТЬ ЭТУ ТАБЛИЦУ НАДО ПАРАМИ, иначе выводы будут неверные:
//   (h прямо, ОДИН блок) = 0.892 -- сам по себе прямой операнд СТОИТ 11%: раскладка операнда даёт
//        16 разных строк на инструкцию против одной широкой LDG.128 при подаче через разделяемую;
//   (h прямо, ДВА блока) = 1.105 -- второй блок даёт +24% и с запасом перекрывает эти 11%.
//   То есть выигрывает НЕ прямой операнд, а ПОРОГ, который он позволяет взять. Приём, у которого
//   собственный знак отрицательный, оказывается верным ходом, потому что снимает ступеньку.
//
// ПОЧЕМУ 1x8, А НЕ 2x4 (обе по 8 варпов). Две причины, обе замерены:
//   1. ГЛОБАЛЬНЫЙ ОПЕРАНД НАДО ЧИТАТЬ ОДИН РАЗ. При сетке WMxWN строки h читают ВСЕ WM рядов варпов,
//      то есть трафик операнда умножается на WM. У 1x8 WM=1 -- каждая строка h читается РОВНО одним
//      варпом; у 2x4 -- двумя (512 LDG на блок против 256). Правило шире геометрии: КОГДА ОПЕРАНД
//      ИДЁТ ИЗ ГЛОБАЛЬНОЙ, СТОРОНУ СЕТКИ ВДОЛЬ ЭТОГО ОПЕРАНДА НАДО ДЕЛАТЬ РАВНОЙ ЕДИНИЦЕ.
//   2. РЕГИСТРЫ. 2x4 с прямым h садится ровно на 128 и РАЗЛИВАЕТСЯ (16 Б кадра, 0.996), 1x8 берёт
//      122 с нулевым кадром. Разница -- в форме накопителя: 4x1 фрагментов против 2x2 при том же
//      числе, но короче диапазоны жизни фрагментов операнда.
//
// ЧТО ПРОВЕРЕНО И НЕ СРАБОТАЛО (не повторять):
//   * ТРЕТИЙ блок на SM. Требует <=32 КБ И <=85 регистров; достижимо (K и V тоже прямо, 26 КБ,
//     80 рег), но ptxas при 80 регистрах РАЗЛИВАЕТСЯ (8 Б кадра) и итог 0.965. Четвёртый -- 0.222
//     при 840 Б кадра. Это ровно §4z: занятость нельзя купить за счёт ресурса, который её заменяет.
//   * V ПРЯМО ИЗ ГЛОБАЛЬНОЙ (V_DIRECT, оставлен параметром). Замысел был верный по форме -- подача V
//     выдаётся ПОСЛЕДНЕЙ, уже после барьера, и стоит на критическом пути открыто. Но замер:
//     0.881->0.899 при T=512, 1.011->1.013 при T=2048, 1.066->1.055 при T=8192, 1.105->1.087 при
//     T=15680; сам по себе (h через smem) -- 0.972..0.985 на ВСЕХ длинах. ПРИЧИНА: подача V через
//     разделяемую КОАЛЕСЦИРОВАНА (uint4 на нить, одна инструкция на 16 Б), а операнд n-мажорный
//     берёт 4 сектора по 32 Б на инструкцию -- вчетверо больше ИНСТРУКЦИЙ MIO на те же байты, а MIO
//     считает инструкции (§4n, §1c). Сэкономленный барьер (33.4 такта) этого не окупает.
//     ЗАКОН: прямой операнд выгоден там, где буфер ЗАНИМАЕТ ПОРОГОВОЕ МЕСТО (h, 34.8 КБ), и невыгоден
//     там, где буфер ЛЕЖИТ ПОВЕРХ ЧУЖОГО и не стоит ничего (sV поверх sK).
//   * ДОПОЛНЕНИЕ PAD=0 (шаг строки 128 полуслов = 64 слова, 64 % 32 == 0): 0.696. Все 16 строк
//     фрагмента садятся в ОДИН банк. PAD=16 -- 1.011 (в пределах шума от PAD=8), PADA=0/4/16 --
//     0.958/1.003/0.997. Дополнение уже стояло в оптимуме; PAD=4 и PAD=12 ВООБЩЕ НЕЗАКОННЫ, см.
//     static_assert ниже.
//   * СЕТКИ 8x1 и 8x2 по выходу НЕВЫРАЗИМЫ: сторона плитки варпа кратна 16 (шаг фрагмента), значит
//     WM <= BT/16 = 4. Это не ограничение кода, а раскладка инструкции.
//   * 16 варпов (4x4, 2x8): 0.900 и 0.916 при одном блоке; при двух блоках регистров остаётся 64 и
//     обе разливаются. 4 варпа -- 0.616..0.827. Восемь варпов -- оптимум с обеих сторон.
//   * sA ПОВЕРХ sQ (минус 9.2 КБ): 1.095 против 1.105 -- порог 48 КБ уже взят, экономия ни во что
//     не конвертируется, а лишний барьер стоит. Откачено (параметр оставлен).
//   * ШИРОКАЯ ПОДАЧА ГЛОБАЛЬНОГО ОПЕРАНДА (WIDE_H, accumulate в volta_warp_mma.h): одна
//     LDG.128 вместо двух LDG.64, глобальных обращений на нить 32 -> 16. По §4n/§1c это должно было
//     быть чистым выигрышем -- MIO считает инструкции. ЗАМЕРЕНО ХУЖЕ: 1.105 -> 1.001 (T=15680),
//     1.066 -> 0.988 (T=8192), при ТЕХ ЖЕ 122 регистрах и нулевом кадре. ПРИЧИНА: закон §1c выведен
//     для РАЗДЕЛЯЕМОЙ памяти, где инструкция и есть ресурс. У глобальной ресурс -- СЕКТОР: 16 строк
//     фрагмента лежат через 256 Б, и вдвое более широкое чтение накрывает ровно те же 16 секторов,
//     не экономя ни одного, зато вдвое укорачивает цикл и лишает планировщик половины независимых
//     обращений в полёте. Правило: "меньше инструкций" -- закон РАЗДЕЛЯЕМОЙ памяти, и переносить его
//     на глобальную с разрывной раскладкой НЕЛЬЗЯ. Параметр оставлен выключенным как след замера.
//   * PADA=4 при победившей геометрии: 1.021 против 1.015 в одном замере и вровень в другом -- шум,
//     0.5 КБ ни во что не конвертируются. Оставлено PADA=8.
//
// ГДЕ ОСТАНОВИЛИСЬ: 0.1968 мс = 491 ГБ/с = 58% от достижимых 841. Оставшийся разрыв -- НЕ геометрия
// (занятость тензорного конвейера у этого ядра инвариантна к плитке, ровно как в PLAYBOOK §12.9):
// это по-прежнему открытая задержка подачи, и следующий рычаг -- программная конвейеризация внутри
// блока (выдать LDG плитки N+1 до барьера плитки N), то есть смена расписания, а не формы.
//
// РАЗДЕЛЯЕМАЯ ПАМЯТЬ И ПЕРЕИСПОЛЬЗОВАНИЕ: sV кладётся ПОВЕРХ sK (V нужен только в G3, когда K уже
// отработал; барьер между ними обязателен). При FUSE_QA=1 ещё и sA ложится поверх sQ.






