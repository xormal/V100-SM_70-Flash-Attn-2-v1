// ВЫБОР ГЕОМЕТРИИ ПО ФОРМЕ.  Выигрыш второго резидентного блока НЕ монотонен по числу блоков, и это
// не шум, а КВАНТОВАНИЕ ВОЛНЫ (VOLTA_SM70 §6), причём у двух ядер оно РАЗНОЕ: у опоры волна = 80
// блоков, у нового ядра = 160. Замерено (отношение к опоре, T -> блоков = NT*H при H=4):
//     T=  512 ->  32 бл : 0.881      T= 2048 -> 128 бл : 1.011
//     T=  768 ->  48 бл : 0.882      T= 3200 -> 200 бл : 1.009
//     T= 1024 ->  64 бл : 0.886      T= 5120 -> 320 бл : 1.116
//     T= 1280 ->  80 бл : 0.984      T= 8192 -> 512 бл : 1.066
//     T= 1536 ->  96 бл : 1.112      T=15680 -> 980 бл : 1.105
//     T= 1920 -> 120 бл : 1.151      T= 2560 -> 160 бл : 0.999
// Ниже 80 блоков машина недозаполнена ОДНИМ блоком на SM -- второму резиденту просто неоткуда
// взяться, и остаются только те 11%, которые стоит прямой операнд. Ровно на 80 и ровно на 160
// блоков опора попадает в целое число волн и идёт вровень. Выше -- новое ядро впереди всегда.
// ПОРОГ: NT*H >= 96. Ниже -- звать ту же функцию с прежними параметрами <BT,DK,DV,2,4,8,8,2,4,
// false,false,1,false>.
__host__ __device__ inline bool gdn_o_use_wide(int blocks) { return blocks >= 96; }

