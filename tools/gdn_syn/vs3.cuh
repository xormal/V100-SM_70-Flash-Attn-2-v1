// РАСКЛАДКИ ОПЕРАНДА B В НАШЕМ API -- ПРОТИВОПОЛОЖНЫ ИНТУИЦИИ ИМЕНИ:
//   kKMajor: B это [N][K], непрерывен K  -> инструкция .row.col, случай Q*K^T
//   kNMajor: B это [K][N], непрерывен N  -> инструкция .row.row, случай P*V
// Отсюда: G1 (h лежит [V][K]) и G2 (k лежит [t][K]) -- ОБА kKMajor; G3 (v лежит [t][V]) -- kNMajor.

// РАЗМЕР РАЗДЕЛЯЕМОЙ ПАМЯТИ -- ОДНА формула на ядро и на хост, чтобы они не разошлись.
// Хвост раскладки внутри ядра ОБЯЗАН повторять эту формулу член в член: рассогласование даёт
// не медленный код, а "illegal memory access" (поймано ровно так при KV_DIRECT).
template <int BT, int DK, int DV, int PAD, int PADA, bool FUSE_QA, bool H_DIRECT = false,
          bool KV_DIRECT = false>
__host__ __device__ constexpr int gdn_o_smem_halves() {
  return BT * (DK + PAD)                                                        // sQ (и sA при FUSE_QA)
       + (H_DIRECT ? 0 : DV * (DK + PAD))                                       // sH
       + (KV_DIRECT ? 0 : (BT * (DK + PAD) > BT * (DV + PAD)
                           ? BT * (DK + PAD) : BT * (DV + PAD)))                // sK, потом sV
       + (FUSE_QA ? 0 : BT * (BT + PADA));                                      // sA
}
template <int BT, int DK, int DV, int PAD, int PADA, bool FUSE_QA, bool H_DIRECT = false,
          bool KV_DIRECT = false>
__host__ __device__ constexpr int gdn_o_smem_bytes() {
  return gdn_o_smem_halves<BT, DK, DV, PAD, PADA, FUSE_QA, H_DIRECT, KV_DIRECT>() * 2;
}

// BT -- размер чанка (64), DK/DV -- размерности головы.
//   WM  x WN   -- сетка варпов по ВЫХОДУ o[BT][DV]         (плитка варпа BT/WM x DV/WN)
//   WMA x WNA  -- сетка варпов по ПРОМЕЖУТОЧНОЙ A[BT][BT]  (плитка варпа BT/WMA x BT/WNA)
// Сетки РАЗНЫЕ намеренно (см. шапку). Ограничение общее: каждая сторона плитки кратна 16 --
// это шаг фрагмента mma.m8n8k4 в нашей раскладке, значит WM,WMA,WNA <= BT/16 и WN <= DV/16.
//
// ЗНАЧЕНИЯ ПО УМОЛЧАНИЮ -- ПОБЕДИТЕЛЬ ПЕРЕБОРА: 1x8 по выходу, 2x4 по A, h прямо из глобальной,
// слитый накопитель, два блока на SM. 43.0 КБ, 122 регистра, кадр 0.
template <int BT, int DK, int DV, int WM = 1, int WN = 8,
          int PAD = 8, int PADA = 8, int WMA = 2, int WNA = 4, bool FUSE_QA = false,
          bool H_DIRECT = true, int MINB = 2, bool FUSE_ACC = true, bool KV_DIRECT = false,
          bool V_DIRECT = false, bool WIDE_H = false>
__global__ __launch_bounds__(WM * WN * 32, MINB) void volta_gdn_chunk_o(
    const __half* __restrict__ q,      // [T, Hg, DK]
    const __half* __restrict__ k,      // [T, Hg, DK]
    const __half* __restrict__ v,      // [T, H,  DV]
    const __half* __restrict__ h,      // [NT, H, DV, DK]   состояние на начало чанка
    const float*  __restrict__ g,      // [T, H]            накопленный логарифм гейта
    __half* __restrict__ o,            // [T, H, DV]
    int T, int H, int Hg, float scale) {
  constexpr int LDQ = DK + PAD, LDV = DV + PAD, LDA = BT + PADA;
  constexpr int SM = BT / WM, SN = DV / WN;      // плитка варпа по выходу
  constexpr int SMA = BT / WMA, SNA = BT / WNA;  // плитка варпа по b_A
  static_assert(WM * WN == WMA * WNA, "обе сетки живут на одном числе варпов");
  static_assert(SM % 16 == 0 && SN % 16 == 0, "плитка выхода кратна шагу фрагмента");
  static_assert(SMA % 16 == 0 && SNA % 16 == 0, "плитка A кратна шагу фрагмента");
  static_assert(!FUSE_QA || BT * LDA <= BT * LDQ, "sA не влезает поверх sQ");
  // §4b: шаг строки, по которой пишут uint4, кратен 16 Б = 8 полусловам. PAD=4 даёт LDQ=132 и
  // ОТКАЗ ЖЕЛЕЗА (misaligned address), а не замедление. Ловится здесь, а не на карте -- и это
  // важно: упавшее ядро портит контекст, и ВСЕ последующие замеры в том же процессе врут.
  static_assert(PAD % 8 == 0, "PAD кратен 8: широкая (uint4) подача строк");
  // Операнд читается uint2 (8 Б) с адреса row*LD -> LD кратно 4 полусловам.
  static_assert(PADA % 4 == 0, "PADA кратен 4: операнд A читается uint2");

  extern __shared__ __half smem[];
  __half* sQ = smem;                                 // [BT][LDQ]
  __half* sH = sQ + BT * LDQ;                        // [DV][LDQ]; при H_DIRECT не размещается
  __half* sK = sH + (H_DIRECT ? 0 : DV * LDQ);       // [BT][LDQ]; позже перекрывается sV
  __half* sV = sK;                                   // ТО ЖЕ МЕСТО, что sK (барьер обязателен)
  __half* sA = FUSE_QA ? sQ
             : sK + (KV_DIRECT ? 0 : (BT * LDQ > BT * LDV ? BT * LDQ : BT * LDV));
  __shared__ float sG[BT];

  const int it = blockIdx.x, ih = blockIdx.y;
  const int NT = (T + BT - 1) / BT;
  if (it >= NT) return;
  const int t0 = it * BT, rows = min(BT, T - t0);
  const int ihg = ih / (H / Hg);                     // голова ключа для GQA-подобного отображения

  const int tid = threadIdx.x, nthr = WM * WN * 32;
  const int lane = tid & 31, warp = tid >> 5;
  const int wm = warp / WN, wn = warp % WN;
  const int wma = warp / WNA, wna = warp % WNA;

  // --- подача. Каждая строка читается ЦЕЛИКОМ широкими обращениями (§1c: MIO считает инструкции).
  for (int i = tid; i < BT * (DK / 8); i += nthr) {
    const int r = i / (DK / 8), c = (i % (DK / 8)) * 8;
    const bool ok = (t0 + r) < T;
    *reinterpret_cast<uint4*>(&sQ[r * LDQ + c]) =
        ok ? *reinterpret_cast<const uint4*>(&q[((long)(t0 + r) * Hg + ihg) * DK + c]) : uint4{0, 0, 0, 0};
    if (!KV_DIRECT)
      *reinterpret_cast<uint4*>(&sK[r * LDQ + c]) =
          ok ? *reinterpret_cast<const uint4*>(&k[((long)(t0 + r) * Hg + ihg) * DK + c]) : uint4{0, 0, 0, 0};
  }
  // K и V прямо из глобальной -- ЭКСПЕРИМЕНТАЛЬНО и по умолчанию ВЫКЛЮЧЕНО (замерено 0.965 из-за
  // разлива при 80 регистрах). Требует T % BT == 0: хвостовой чанк иначе читает за концом.
  const __half* kb = &k[((long)t0 * Hg + ihg) * DK];
  const __half* vb = &v[((long)t0 * H + ih) * DV];

  // СОСТОЯНИЕ h -- 32 КБ на блок, ОДНО чтение, НУЛЕВОЕ переиспользование (ни внутри блока, ни между
  // блоками: пара (чанк, голова) владеет своим срезом целиком). Поэтому промежуточная станция в
  // разделяемой памяти не покупала ничего, а стоила 34.8 КБ -- ровно тех, из-за которых блок был
  // один на SM. H_DIRECT=1 отдаёт h прямо в операнд B.
  // ЦЕНА РАСКЛАДКИ, честно: операнд kKMajor берёт строку на полосу, строки h идут через 256 Б,
  // значит 16 разных секторов на LDG против одной LDG.128 при подаче через разделяемую. Но
  // 128-байтовая линия L1 кроет 16 шагов k, поэтому промах ОДИН на 16 обращений, а суммарный трафик
  // тот же. Замер: сам приём -0.892, вместе со вторым блоком +1.105.
  const __half* hb = &h[((long)it * H + ih) * DV * DK];
  if (!H_DIRECT) {
    for (int i = tid; i < DV * (DK / 8); i += nthr) {
      const int r = i / (DK / 8), c = (i % (DK / 8)) * 8;
      *reinterpret_cast<uint4*>(&sH[r * LDQ + c]) = *reinterpret_cast<const uint4*>(&hb[r * DK + c]);
    }
  }
  for (int i = tid; i < BT; i += nthr) sG[i] = (t0 + i) < T ? g[(long)(t0 + i) * H + ih] : 0.f;
  __syncthreads();

  // --- G1 и G2: у обоих B имеет вид [N][K] с непрерывным K, то есть kKMajor.
  WarpMma<SM / 16, SN / 16, BLayout::kKMajor> mo;
  WarpMma<SMA / 16, SNA / 16, BLayout::kKMajor> ma;
  mo.clear(); ma.clear();
  // WIDE_H: у k-мажорного операнда шаг k идёт по строке подряд, поэтому ОДНА LDG.128 кроет ДВА шага
  // и вдвое режет число ГЛОБАЛЬНЫХ обращений (32 -> 16 на нить).
  if (H_DIRECT && WIDE_H)  mo.template accumulate<DK>(sQ, LDQ, wm * SM, hb, DK, wn * SN, lane);
  else if (H_DIRECT)       mo.template accumulate<DK>(sQ, LDQ, wm * SM, hb, DK, wn * SN, lane);
  else                     mo.template accumulate<DK>(sQ, LDQ, wm * SM, sH, LDQ, wn * SN, lane);
  if (KV_DIRECT) ma.template accumulate<DK>(sQ, LDQ, wma * SMA, kb, Hg * DK, wna * SNA, lane);
  else           ma.template accumulate<DK>(sQ, LDQ, wma * SMA, sK, LDQ, wna * SNA, lane);

  // --- гейты и причинная маска ВНУТРИ чанка.
  // b_o *= e^{g_t};  b_A[t][s] *= e^{g_t - g_s} и обнуляется при s > t.
  // Обе поправки поэлементны по накопителю -- то есть свободный слот FP32 под HMMA (§4p).
  const int ro = wm * SM, co = wn * SN, roa = wma * SMA, ca = wna * SNA;
  mo.visit(lane, [&](float& x, int r, int c) { x *= __expf(sG[ro + r]); });
  ma.visit(lane, [&](float& x, int r, int c) {
    const int tt = roa + r, ss = ca + c;
    x = (ss <= tt && tt < rows && ss < rows) ? x * __expf(sG[tt] - sG[ss]) : 0.f;
  });

  // --- tril(A) в разделяемую (в fp16, как операнд третьего умножения)
  if (FUSE_QA) __syncthreads();          // sA ложится ПОВЕРХ sQ -> дождаться конца G1/G2
  ma.visit(lane, [&](float& x, int r, int c) { sA[(roa + r) * LDA + ca + c] = __float2half(x); });
  __syncthreads();                       // sA готова; sK больше не нужен -> его место занимает sV

  // V_DIRECT ЗАМЕРЕН И ОТКЛОНЁН (см. шапку): подача V через разделяемую коалесцирована (uint4 на
  // нить), а n-мажорный операнд берёт 4 сектора по 32 Б на инструкцию -- вчетверо больше инструкций
  // MIO на те же байты. Оставлен параметром как след замера. Хвостовой чанк (rows < BT) идёт прежним
  // путём в любом случае: условие блочно-однородное, барьеры не расходятся.
  const bool vdir = V_DIRECT && (rows == BT);
  if (!KV_DIRECT && !vdir) {
    for (int i = tid; i < BT * (DV / 8); i += nthr) {
      const int r = i / (DV / 8), c = (i % (DV / 8)) * 8;
      const bool ok = (t0 + r) < T;
      *reinterpret_cast<uint4*>(&sV[r * LDV + c]) =
          ok ? *reinterpret_cast<const uint4*>(&v[((long)(t0 + r) * H + ih) * DV + c]) : uint4{0, 0, 0, 0};
    }
    __syncthreads();
  }

  // --- G3: += tril(A) x V. V лежит [t][v] с непрерывным v, то есть [K][N] -> kNMajor.
  // FUSE_ACC: карта аккумулятора ОДНА для всех четырёх вариантов инструкции (замерено,
  // volta_warp_mma.h), поэтому третье умножение ПРОДОЛЖАЕТ накопитель первого, а не заводит свой.
  // Экономит SM/16 * SN/16 * 8 регистров (здесь 32) и целый проход сложения; по времени -- шум,
  // но 122 регистра вместо 128 держат запас до обрыва: 128*256 = 32768 это РОВНО половина файла,
  // и один лишний регистр стоил бы второго блока и 11%.
  WarpMma<SM / 16, SN / 16, BLayout::kNMajor> mv;
  if (FUSE_ACC) {
#pragma unroll
    for (int i = 0; i < SM / 16; ++i)
#pragma unroll
      for (int j = 0; j < SN / 16; ++j)
#pragma unroll
        for (int r = 0; r < 8; ++r) mv.acc[i][j][r] = mo.acc[i][j][r];
  } else {
    mv.clear();
  }
  if (KV_DIRECT || vdir) mv.template accumulate<BT>(sA, LDA, wm * SM, vb, H * DV, wn * SN, lane);
  else                   mv.template accumulate<BT>(sA, LDA, wm * SM, sV, LDV, wn * SN, lane);
#pragma unroll
  for (int i = 0; i < SM / 16; ++i)
#pragma unroll
    for (int j = 0; j < SN / 16; ++j)
#pragma unroll
      for (int r = 0; r < 8; ++r)
        mv.acc[i][j][r] = (FUSE_ACC ? mv.acc[i][j][r] : mv.acc[i][j][r] + mo.acc[i][j][r]) * scale;

  // --- запись
  mv.visit(lane, [&](float& x, int r, int c) {
    const int tt = ro + r;
    if (tt < rows) o[((long)(t0 + tt) * H + ih) * DV + co + c] = __float2half(x);
  });
}

