"""Проверка ЛОГИКИ кэша общих индексов (рычаг FA2SM70_GDN_SHARE_IDX) на процессоре.
Правка написана без возможности замера (карта 0 отвалилась), поэтому её логику обязан
проверить отдельный прибор: кэшированный путь должен давать ПОБАЙТОВО то же, что прямой,
на всех слоях и на краевых случаях.
"""
import torch

def прямой(spec_idx, нсд2, Wд, Т2, dev="cpu"):
    слот0 = spec_idx[:нсд2, 0].to(torch.long).clamp(min=0)
    ряд = torch.arange(max(нсд2, 0), device=dev)
    инд_B = torch.cat([
        (ряд * Т2).unsqueeze(1),
        (ряд * Т2).unsqueeze(1) + Wд + 1 + torch.arange(Wд, device=dev).unsqueeze(0),
    ], dim=1).reshape(-1)
    return слот0, ряд, инд_B, ряд.to(torch.int32), \
        torch.arange(нсд2 + 1, device=dev, dtype=torch.int32) * (Wд + 1)

class Мета:            # подделка объекта метаданных: он создаётся заново каждый шаг
    pass

def с_кэшем(мета, spec_idx, нсд2, Wд, Т2, dev="cpu"):
    ключ = (int(нсд2), int(Wд), int(Т2))
    общ = getattr(мета, "_fa2_общ_идx", None)
    if общ is not None and общ[0] == ключ:
        return общ[1], True
    знач = прямой(spec_idx, нсд2, Wд, Т2, dev)
    мета._fa2_общ_идx = (ключ, знач)
    return знач, False

плохо = 0
for нсд2, Wд in ((4,3),(8,3),(1,3),(0,3),(16,4),(2,1),(64,3)):
    Т2 = 2*Wд + 1
    spec = torch.randint(-1, 1000, (max(нсд2,1), 8), dtype=torch.int32)
    мета = Мета()
    эталон = прямой(spec, нсд2, Wд, Т2)
    попаданий = 0
    for слой in range(48):                       # 48 слоёв GDN за один шаг
        знач, попал = с_кэшем(мета, spec, нсд2, Wд, Т2)
        попаданий += int(попал)
        for i,(a,b) in enumerate(zip(знач, эталон)):
            if a.shape != b.shape or not torch.equal(a,b):
                print(f"  РАСХОЖДЕНИЕ нсд2={нсд2} Wд={Wд} слой={слой} поле={i}"); плохо += 1
    ок = (попаданий == 47)
    print(f"  нсд2={нсд2:3d} Wд={Wд}: попаданий кэша {попаданий}/47 {'ОК' if ок else 'НЕВЕРНО'}, "
          f"все 48 слоёв сошлись с прямым путём: {'да' if плохо==0 else 'НЕТ'}")
    if not ок: плохо += 1
# краевой случай: в ОДНОМ шаге сменилось нсд2 (не должно брать старый кэш)
мета = Мета(); spec = torch.randint(0, 100, (16, 8), dtype=torch.int32)
с_кэшем(мета, spec, 4, 3, 7); знач, попал = с_кэшем(мета, spec, 8, 3, 7)
эт = прямой(spec, 8, 3, 7)
сошлось = all(torch.equal(a,b) for a,b in zip(знач, эт))
print(f"  смена нсд2 в том же объекте: кэш {'НЕ взят (верно)' if not попал else 'ВЗЯТ (ОШИБКА)'}, "
      f"значения верны: {сошлось}")
if попал or not сошлось: плохо += 1
print(f"\nИТОГ: {'ЛОГИКА ВЕРНА' if плохо==0 else f'ДЕФЕКТОВ {плохо}'}")
