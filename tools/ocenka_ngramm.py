"""ОЦЕНКА ГИБРИДА «n-грамма или MTP» -- офлайн, по НАСТОЯЩЕЙ выдаче модели.

Вопрос: как часто при генерации ПРОЗЫ n-граммный черновик вообще срабатывает и сколько
позиций угадывает. Память говорит: на повторяемом тексте приёмка 3.86 и 71.6 ток/с; вопрос
только в доле срабатываний на прозе. Считаем ровно то, что делает NgramProposer: ищем
последние n токенов раньше в последовательности и берём k следующих.
"""
import sys
from transformers import AutoTokenizer
MD="/mnt/d1/alex/VLLM_ch/Qwen3.8-27B-ABL_int8_i12"
tok=AutoTokenizer.from_pretrained(MD, trust_remote_code=True)
текст=open(sys.argv[1],encoding="utf-8").read()
ид=tok(текст,add_special_tokens=False)["input_ids"]
print(f"токенов в выдаче: {len(ид)}")
K=3
for N in (2,3,4):
    сраб=0; принято=0; всего=0
    поз={}                                  # последнее вхождение n-граммы
    for i in range(len(ид)-1):
        всего+=1
        ключ=tuple(ид[max(0,i-N+1):i+1])
        j=поз.get(ключ)
        if j is not None and j+1 < len(ид):
            сраб+=1
            # сколько подряд угадано из k
            п=0
            for t in range(K):
                if j+1+t < len(ид) and i+1+t < len(ид) and ид[j+1+t]==ид[i+1+t]: п+=1
                else: break
            принято+=п
        поз[ключ]=i
    доля=сраб/всего*100
    ср=принято/сраб if сраб else 0
    # tau гибрида: где сработало -- 1+принято, где нет -- нынешняя 2.42
    tau=(принято+сраб)/всего + (всего-сраб)/всего*2.42
    print(f"  n={N}: срабатывает {доля:5.1f}% позиций, при срабатывании угадано {ср:.2f} из {K}"
          f"  ->  tau гибрида ~{tau:.2f} (нынешняя 2.42)")
