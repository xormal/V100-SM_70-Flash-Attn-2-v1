#!/usr/bin/env python3
"""ИНДЕКС ЧАСТЫХ ТОКЕНОВ ДЛЯ СРЕЗА СЛОВАРЯ ЧЕРНОВИКА.

ЗАЧЕМ. Верхушка словаря черновика -- вторая по величине фаза `propose` (2.60 мс из 9.45) и
связана ЧТЕНИЕМ: голова 248320x5120 fp16 -- это 1.27 ГБ на ранг. int8 её ускоряет, но кладёт
ОТДЕЛЬНУЮ раскладку +606 МиБ на ранг и роняет длинный контекст в OOM (записка 25 §212).
Срез снимает обе беды разом: 32K строк в int8 -- 0.16 ГиБ вместо 1.19.

ПОЧЕМУ ЭТО БЕЗОПАСНО ДЛЯ КАЧЕСТВА. Черновик только ПРЕДЛАГАЕТ; каждый его токен проверяет
цель. Токен вне среза не может быть предложен -- это стоит ПРИЁМКИ, но не правильности.
Значит гейт здесь -- tau, а не совпадение ответов.

Частоты берутся из корпуса, собранного самим боевым путём (настоящие токены позиций).

  python3 dflash2_srez_slovarya.py <корпус> <выход.pt> [размер]
"""
import sys, os, glob, collections
import torch

def main():
    корпус = sys.argv[1] if len(sys.argv) > 1 else "/mnt/d1/alex/dflash2_syryo"
    выход = sys.argv[2] if len(sys.argv) > 2 else "/mnt/d1/alex/dflash2_vocab32k.pt"
    размер = int(sys.argv[3]) if len(sys.argv) > 3 else 32768
    файлов = int(os.environ.get("FILES", "600"))
    счёт = collections.Counter()
    всего = 0
    файлы = sorted(glob.glob(os.path.join(корпус, "*.pt")))
    for ф in файлы[:файлов]:
        try:
            пары = torch.load(ф, map_location="cpu")
        except Exception:
            continue
        for п in пары:
            if len(п) < 5 or п[4] is None:
                continue
            m = max(1, min(int(п[2]), п[4].shape[0]))
            for т in п[4][:m].tolist():
                счёт[int(т)] += 1; всего += 1
    print(f"  токенов в счёте: {всего}, различных: {len(счёт)}")
    частые = [т for т, _ in счёт.most_common(размер)]
    # СЛУЖЕБНЫЕ ВСЕГДА ВНУТРИ. Их частота в корпусе низка (eos встречается раз на ответ), а
    # выпадение eos из среза означало бы, что черновик НИКОГДА не предложит конец -- то есть
    # систематический отказ ровно на последней позиции каждого ответа.
    служебные = [248044, 248070] + list(range(248000, 248320))
    ид = sorted(set(частые) | set(служебные))
    покрытие = sum(счёт[т] for т in ид) / max(всего, 1)
    print(f"  срез: {len(ид)} строк, ПОКРЫТИЕ корпуса {покрытие*100:.3f} %")
    # Отложенная проверка: покрытие на файлах, НЕ вошедших в счёт.
    прочие = 0; попало = 0
    множ = set(ид)
    for ф in файлы[файлов:файлов + 120]:
        try:
            пары = torch.load(ф, map_location="cpu")
        except Exception:
            continue
        for п in пары:
            if len(п) < 5 or п[4] is None:
                continue
            m = max(1, min(int(п[2]), п[4].shape[0]))
            for т in п[4][:m].tolist():
                прочие += 1; попало += int(int(т) in множ)
    if прочие:
        print(f"  ОТЛОЖЕННОЕ покрытие: {попало/прочие*100:.3f} % ({прочие} токенов)")
    torch.save(torch.tensor(ид, dtype=torch.long), выход)
    print(f"  сохранено: {выход}")

if __name__ == "__main__":
    main()
