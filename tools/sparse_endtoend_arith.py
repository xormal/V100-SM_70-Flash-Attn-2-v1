"""СВОДНАЯ АРИФМЕТИКА: от ЗАМЕРЕННОЙ цены механизма и ЗАМЕРЕННОГО качества отборщика -- к секундам
префилла на 250K. Никаких новых допущений: только два замера этой сессии и раскладка из задания.

Замер 1 (benchmarks/bench_sparse_mech.py, V100, B1 H12 Hkv2 Sq8192 Sk65536, чередующийся протокол):
    подача маски битовой картой   +0.40% ВСЕГДА
    подача маски списком          +7.25% ВСЕГДА  (отвергнута)
    сводки (только новый чанк)     0.02% внимания
    отбор плиток                   1.52% внимания
    постоянная часть задания F     4.0% плотного времени (подгонка t = F + c*n по свипу плотности)
Замер 2 (tools/sparse_selector_vs_oracle.py, НАСТОЯЩИЙ дамп Q/K/V, 4 слоя x все головы x 12 блоков):
    relL2 выхода при отборе оракула и при РЕАЛИЗУЕМОМ отборе (средний ключ + LSE по запросам).
"""
import numpy as np

DENS = np.array([0.50, 0.65, 0.75, 0.85, 0.95])
# слой модели -> relL2 (агрегат по всем головам), замер этой сессии
ORACLE = {3:  [6.47e-2, 4.01e-2, 2.76e-2, 1.73e-2, 7.79e-3],
          23: [7.50e-2, 4.21e-2, 2.60e-2, 1.38e-2, 4.15e-3],
          43: [2.73e-2, 1.38e-2, 7.92e-3, 3.77e-3, 9.34e-4],
          63: [1.56e-2, 8.79e-3, 5.22e-3, 2.69e-3, 7.69e-4]}
REAL = {3:  [6.94e-2, 4.28e-2, 2.94e-2, 1.84e-2, 7.34e-3],
        23: [1.26e-1, 8.38e-2, 6.20e-2, 4.02e-2, 1.47e-2],
        43: [5.90e-2, 3.89e-2, 3.02e-2, 2.21e-2, 8.55e-3],
        63: [2.55e-2, 1.55e-2, 1.01e-2, 5.66e-3, 2.74e-3]}

# Калибровка по ЗАМЕРУ НА РАЗВЁРНУТОЙ ФОРМЕ (Sq=16384, Sk=249856, H=12, Hkv=2 -- чанк и контекст
# сервера), а не на удобной маленькой: и постоянная часть задания, и цена подачи маски от формы
# ЗАВИСЯТ, и на 65K обе выглядят вдвое безобиднее.
#   EFF -- какую долю идеального 1/p механизм донёс до конца при СОГЛАСОВАННЫХ масках (общих на
#          группу из G>=4 блоков запросов): замерено 96.4% при p=0.60 и 97.1% при p=0.835 -> 0.965.
#          Внутрь EFF уже входят постоянная часть задания (заливка Q, эпилог) и подача маски картой.
#   EFF_UNCOORD -- то же при НЕСОГЛАСОВАННЫХ масках (каждый блок запросов отбирает сам):
#          87.4% при p=0.60 и 81.6% при p=0.835. При высокой плотности это делает разреженность
#          УБЫТОЧНОЙ: замерено 0.978x, то есть медленнее плотного внимания.
#   SEL -- сводки нового чанка (0.01%) + отбор плиток (1.57%), в долях ПЛОТНОГО времени внимания.
EFF = 0.965
EFF_UNCOORD = 0.82
SEL = 0.0158


def dens_for(err_curve, budget):
    """Какая плотность укладывается в бюджет. Интерполяция ЛОГАРИФМА ошибки по плотности --
    ошибка убывает с плотностью примерно геометрически, и линейная интерполяция по ней завышала бы
    достижимую плотность. Ниже 0.50 и выше 0.95 -- экстраполяция по крайнему наклону, помечается."""
    e = np.log(np.array(err_curve)); b = np.log(budget)
    # e убывает с плотностью -> ищем плотность, где e == b
    if b >= e[0]:
        return 0.50, "<=0.50 (экстраполяция)"
    if b <= e[-1]:
        sl = (e[-1] - e[-2]) / (DENS[-1] - DENS[-2])
        d = DENS[-1] + (b - e[-1]) / sl
        return min(d, 1.0), (">=0.95" if d < 1.0 else "1.00 (несжимаем)")
    d = float(np.interp(b, e[::-1], DENS[::-1]))
    return d, ""


def speedup(p, eff=EFF):
    """Ускорение ВНИМАНИЯ при плотности p с учётом ВСЕХ замеренных накладных."""
    return 1.0 / (p / eff + SEL)


def main():
    for budget, label in ((1.8e-2, "e4m3 (KV сейчас)"), (3.0e-2, "int8+масштаб (задача #86)")):
        print(f"\n=== БЮДЖЕТ РАЗРЕЖЕННОСТИ {budget:.1e}  [{label}] ===")
        print(f'{"слой":>5} {"оракул p":>10} {"реализуемо p":>13} {"плата за реализуемость":>23}')
        po, pr = [], []
        for L in (3, 23, 43, 63):
            do, no = dens_for(ORACLE[L], budget)
            dr, nr = dens_for(REAL[L], budget)
            po.append(do); pr.append(dr)
            print(f'{L:>5} {do:>10.3f} {dr:>13.3f} {"+" + f"{(dr-do):.3f}":>15}  {nr}')
        # 16 слоёв полного внимания идут каждый 4-й: интерполируем по глубине между замеренными
        Ls = np.arange(3, 64, 4)
        pom = float(np.mean(np.interp(Ls, [3, 23, 43, 63], po)))
        prm = float(np.mean(np.interp(Ls, [3, 23, 43, 63], pr)))
        print(f'  СРЕДНЯЯ ПО 16 СЛОЯМ ПОЛНОГО ВНИМАНИЯ: оракул {pom:.3f}, реализуемо {prm:.3f}')
        so, sr = speedup(pom), speedup(prm)
        print(f'  ускорение внимания:                   оракул {so:.3f}x, реализуемо {sr:.3f}x')
        # Раскладка из задания. NB: слагаемые дают 209.0, а ИТОГО в задании 204.5 -- расхождение
        # 4.5 с в самой раскладке. Считаю от ЗАЯВЛЕННОГО итога 204.5 и от ЭКОНОМИИ на внимании,
        # чтобы вывод не зависел от того, как закрыть эту невязку.
        att, tot0 = 139.7, 204.5
        for nm, s in (("оракул (потолок)", so), ("НАШ отборщик (замер)", sr)):
            a2 = att / s
            print(f'  250K, {nm:<22} внимание {att:.1f} -> {a2:.1f} с (экономия {att-a2:.1f} с), '
                  f'ИТОГО {tot0:.1f} -> {tot0-(att-a2):.1f} с  = x{tot0/(tot0-(att-a2)):.3f}')
    print("\n--- итог механизма при плотности p (развёрнутая форма, все накладные вычтены) ---")
    print(f'{"p":>6} {"идеал 1/p":>10} {"согласованные маски":>20} {"НЕсогласованные":>17}')
    for p in (0.90, 0.835, 0.80, 0.75, 0.70, 0.60, 0.50):
        print(f'{p:>6.3f} {1/p:>9.3f}x {speedup(p):>19.3f}x {speedup(p, EFF_UNCOORD):>16.3f}x')
    print("  «НЕсогласованные» -- каждый блок запросов отбирает плитки САМ. При p >= 0.85 это УБЫТОК:")
    print("  выброшенная работа не окупает потерянного переиспользования K/V между заданиями.")


if __name__ == "__main__":
    main()
