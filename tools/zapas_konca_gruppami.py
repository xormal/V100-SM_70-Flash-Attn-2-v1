import json, statistics, sys, urllib.request
БАЗА="http://127.0.0.1:8095"; МОДЕЛЬ="Qwen3.6-27B-AWQ"
ЦВЕТА=["ЖЁЛТЫЙ","СИНИЙ","ЗЕЛЁНЫЙ","КРАСНЫЙ","ЧЁРНЫЙ","БЕЛЫЙ","СЕРЫЙ","РЫЖИЙ"]
НАПОЛНИТЕЛЬ=("Настоящий раздел содержит служебные сведения о порядке ведения "
             "складского учёта. Записи вносятся в журнал по мере поступления. "
             "Ответственный сотрудник заверяет каждую страницу. Копии хранятся "
             "в архиве организации согласно установленному регламенту. ")
def зов(п,т,to=900):
    з=urllib.request.Request(БАЗА+п,data=json.dumps(т).encode(),headers={"Content-Type":"application/json"})
    with urllib.request.urlopen(з,timeout=to) as ф: return json.load(ф)
нб=зов("/tokenize",{"model":МОДЕЛЬ,"prompt":НАПОЛНИТЕЛЬ},300)["count"]
блоки=[НАПОЛНИТЕЛЬ]*max(16,8000//max(1,нб))
for i in range(8):
    поз=min(len(блоки)-1,int(len(блоки)*((i+0.5)/8)))
    блоки.insert(поз,f"\n\nВАЖНО: кодовое слово склада номер {i+1} — {ЦВЕТА[i]}.\n\n")
осн="".join(блоки)+("\n\nВопрос. Выше по тексту встречались кодовые слова складов. Перечисли ВСЕ "
                    "из них в формате «склад N — КОД», по одному на строку. Ничего не добавляй.")
def прогон(сдв):
    о=зов("/v1/chat/completions",{"model":МОДЕЛЬ,"max_tokens":220,"temperature":0.0,
          "logprobs":True,"top_logprobs":20,
          "messages":[{"role":"user","content":("слово "*сдв)+осн}]})
    c,u=о["choices"][0],о["usage"]; вх=u["prompt_tokens"]
    зап={}
    for i,ш in enumerate(((c.get("logprobs") or {}).get("content") or [])):
        топ=ш.get("top_logprobs") or []
        л1=топ[0]["logprob"] if топ else ш["logprob"]
        к=next((т["logprob"] for т in топ if "im_end" in (т["token"] or "")),None)
        if к is not None: зап[i]=л1-к
    текст=c["message"]["content"] or ""
    return вх,зап,u["completion_tokens"],sum(1 for ц in ЦВЕТА if ц in текст)
ПЕРЕС=[70,107,140]; БЕЗ=[160,200,250]
данные={}
for сдв in ПЕРЕС+БЕЗ:
    вх,зап,n,найд=прогон(сдв)
    данные[сдв]=(вх,зап,n,найд)
    пересек = вх < 8192 <= вх+n
    print(f"  сдвиг={сдв:>3} вход={вх} выход={n:>3} найдено={найд}/8 "
          f"{'ПЕРЕСЕКАЕТ' if пересек else 'нет пересечения'} "
          f"шагов_с_концом={len(зап)}")
общие=set.intersection(*[set(данные[с][1]) for с in данные]) if данные else set()
print(f"\n  общих шагов (конец в топ-20 у ВСЕХ шести): {len(общие)}")
if общие:
    ср={с:statistics.mean(данные[с][1][i] for i in общие) for с in данные}
    гп=[ср[с] for с in ПЕРЕС]; гб=[ср[с] for с in БЕЗ]
    for с in ПЕРЕС+БЕЗ:
        print(f"    сдвиг={с:>3}: средний запас конца {ср[с]:6.2f} nat "
              f"({'пересечение' if с in ПЕРЕС else 'без'})")
    print(f"\n  ГРУППА С ПЕРЕСЕЧЕНИЕМ: {statistics.mean(гп):6.2f} nat "
          f"(разброс {max(гп)-min(гп):.2f})")
    print(f"  ГРУППА БЕЗ:            {statistics.mean(гб):6.2f} nat "
          f"(разброс {max(гб)-min(гб):.2f})")
    print(f"  ЦЕНА ПЕРЕХОДА: {statistics.mean(гп)-statistics.mean(гб):+.2f} nat")
