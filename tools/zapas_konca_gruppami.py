# ЗАМЕР 06.09 (k=3, боевая конфигурация):
#   боевая (GRAN_SRC=1, GRAN_CONV=0): цена -1.55 nat, пол 0.65 -- дефект ЕСТЬ
#   без спекуляции:                   цена -0.37 nat (парная проба) -- дефекта НЕТ
#   FA2SM70_GRAN_ALWAYS=1:            цена -2.22 nat -- подстановка блока-источника НЕ лечит
#   FA2SM70_GRAN_CONV=1:              цена +0.11 nat, но разброс группы 8.64 против 0.35 --
#                                     среднее выправлено, устойчивость потеряна
#
# Сравнивать МОЖНО ТОЛЬКО ВНУТРИ ОДНОГО ПОДЪЁМА: абсолютный уровень запаса гуляет
# между подъёмами (13.4 против 9.2 нат), а разность групп -- нет.
