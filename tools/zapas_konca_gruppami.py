# величина -- запас логита конца (лидер минус <|im_end|>) -- ГРУППАМИ: три промпта,
# у которых ответ ПЕРЕСЕКАЕТ кратное 4096, против трёх, у которых не пересекает.
# Разброс ВНУТРИ группы «без пересечения» -- это шум длины промпта (пол прибора),
# разность СРЕДНИХ между группами -- цена перехода.
