def зов(п,т,to=900):
    з=urllib.request.Request(БАЗА+п,data=json.dumps(т).encode(),headers={"Content-Type":"application/json"})
    with urllib.request.urlopen(з,timeout=to) as ф: return json.load(ф)
нб=зов("/tokenize",{"model":МОДЕЛЬ,"prompt":НАПОЛНИТЕЛЬ},300)["count"]
блоки=[НАПОЛНИТЕЛЬ]*max(16,8000//max(1,нб))
for i in range(8):
    поз=min(len(блоки)-1,int(len(блоки)*((i+0.5)/8)))
    блоки.insert(поз,f"\n\nВАЖНО: кодовое слово склада номер {i+1} — {ЦВЕТА[i]}.\n\n")
осн="".join(блоки)+("\n\nВопрос. Выше по тексту встречались кодовые слова складов. Перечисли ВСЕ "
                    "из них в формате «склад N — КОД», по одному на строку. Ничего не добавляй.")
def прогон(сдв):
    о=зов("/v1/chat/completions",{"model":МОДЕЛЬ,"max_tokens":220,"temperature":0.0,
          "logprobs":True,"top_logprobs":20,
          "messages":[{"role":"user","content":("слово "*сдв)+осн}]})
    c,u=о["choices"][0],о["usage"]
    ряд=[]
    for ш in ((c.get("logprobs") or {}).get("content") or []):
        топ=ш.get("top_logprobs") or []
        л1=топ[0]["logprob"] if топ else ш["logprob"]
        к=next((т["logprob"] for т in топ if "im_end" in (т["token"] or "")),None)
        ряд.append((л1,к,ш["token"]))
    return u["prompt_tokens"],ряд,c["finish_reason"],(c["message"]["content"] or "")
вхA,A,fA,тA=прогон(107); вхB,B,fB,тB=прогон(250)
грA=8192-вхA
print(f"A: вход={вхA} шагов={len(A)} finish={fA} найдено={sum(1 for ц in ЦВЕТА if ц in тA)}/8 пересечение на шаге {грA}")
print(f"B: вход={вхB} шагов={len(B)} finish={fB} найдено={sum(1 for ц in ЦВЕТА if ц in тB)}/8 пересечения нет")
n=min(len(A),len(B))
print("\nшаг  токен      запас_конца A   запас_конца B   разница")
пары=[]
for i in range(n):
    a,b=A[i],B[i]
    зa = None if a[1] is None else a[0]-a[1]
    зb = None if b[1] is None else b[0]-b[1]
    if зa is None and зb is None: continue
    d = "-" if (зa is None or зb is None) else f"{зa-зb:+.2f}"
    пары.append((i,зa,зb))
    метка = "<-- после границы" if 0 <= i-грA <= 8 else ""
    print(f"{i:>3}  {a[2]!r:<10} {'-' if зa is None else f'{зa:6.2f}':>8}  "
          f"{'-' if зb is None else f'{зb:6.2f}':>13}  {d:>8}  {метка}")
об=[(i,зa,зb) for i,зa,зb in пары if зa is not None and зb is not None]
if об:
    вн=[зa-зb for i,зa,зb in об if not (0<=i-грA<=8)]
    у=[зa-зb for i,зa,зb in об if 0<=i-грA<=8]
    print(f"\nсредняя разница запаса ВНЕ окна границы: {sum(вн)/len(вн):+.2f} nat ({len(вн)} шагов)")
    if у: print(f"средняя разница запаса В окне границы: {sum(у)/len(у):+.2f} nat ({len(у)} шагов)")
